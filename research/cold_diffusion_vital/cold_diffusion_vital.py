class EMA:
    """Exponential moving average of the weights (with the usual warm-up of the decay)."""

    def __init__(self, model: nn.Module, decay: float = 0.999):
        self.decay = decay
        self.model = copy.deepcopy(model).eval()
        for p in self.model.parameters():
            p.requires_grad_(False)

    @torch.no_grad()
    def update(self, model: nn.Module, step: int):
        d = min(self.decay, (1 + step) / (10 + step))
        for e, m in zip(self.model.parameters(), model.parameters()):
            e.lerp_(m.detach(), 1 - d)
        for e, m in zip(self.model.buffers(), model.buffers()):
            e.copy_(m)

    def state_dict(self):
        return self.model.state_dict()

    def load_state_dict(self, sd):
        self.model.load_state_dict(sd)


def _make_grad_scaler(enabled: bool):
    try:
        return torch.amp.GradScaler("cuda", enabled=enabled)
    except (AttributeError, TypeError):
        return torch.cuda.amp.GradScaler(enabled=enabled)


PRIOR_BUFFERS = ("prior_mean", "prior_factor", "prior_ready")


class Trainer:
    """
    Training loop with: AdamW + warm-up/cosine schedule, AMP (bf16 or fp16 + GradScaler),
    gradient accumulation and clipping, EMA, deterministic validation, automatic resumption
    from the latest checkpoint (model, EMA, optimiser, scheduler, scaler, RNG, curves),
    best-model tracking, train-vs-valid curves and periodic visual snapshots.
    """

    def __init__(self, model: ColdDiffusionModel, train_dataset: Dataset, val_dataset: Dataset, config: Config):
        self.cfg = cfg = config
        self.device = torch.device(cfg.device)
        self.model = model.to(self.device)
        self.train_dataset, self.val_dataset = train_dataset, val_dataset
        pin = self.device.type == "cuda"
        nw = cfg.num_workers
        self.train_loader = DataLoader(train_dataset, batch_size=cfg.batch_size, shuffle=True, num_workers=nw,
                                       pin_memory=pin, drop_last=len(train_dataset) > cfg.batch_size,
                                       persistent_workers=nw > 0)
        self.val_loader = DataLoader(val_dataset, batch_size=cfg.batch_size, shuffle=False, num_workers=nw,
                                     pin_memory=pin, persistent_workers=nw > 0)
        self.loss_fn = ColdDiffusionLoss(cfg).to(self.device)
        self.optimizer = optim.AdamW(self._param_groups(), lr=cfg.learning_rate, betas=tuple(cfg.betas), eps=1e-8)
        self.steps_per_epoch = max(1, math.ceil(len(self.train_loader) / cfg.grad_accum_steps))
        self.total_steps = max(1, cfg.epochs * self.steps_per_epoch)

        warmup, total, floor = cfg.warmup_steps, self.total_steps, cfg.min_lr_ratio

        def lr_lambda(step):  # plain function -> not pickled into the scheduler state
            if step < warmup:
                return float(step + 1) / float(max(1, warmup))
            progress = min(1.0, float(step - warmup) / float(max(1, total - warmup)))
            return floor + (1 - floor) * 0.5 * (1.0 + math.cos(math.pi * progress))

        self.scheduler = optim.lr_scheduler.LambdaLR(self.optimizer, lr_lambda)
        self.use_amp = cfg.use_amp and self.device.type == "cuda"
        self.amp_dtype = torch.bfloat16 if (self.use_amp and torch.cuda.is_bf16_supported()) else torch.float16
        self.scaler = _make_grad_scaler(self.use_amp and self.amp_dtype == torch.float16)
        self.ema = EMA(self.model, cfg.ema_decay) if cfg.use_ema else None

        self.current_epoch = 0
        self.global_step = 0
        self.best_metric = -float("inf")
        self.history: Dict[str, List[Any]] = {"epoch": []}
        self.lr_history: List[float] = []
        self.checkpoint_dir = Path(cfg.checkpoint_dir)
        self.checkpoint_dir.mkdir(parents=True, exist_ok=True)
        self.viz_dir = Path(cfg.visualization_dir) / "training"
        self.viz_dir.mkdir(parents=True, exist_ok=True)
        # Resume *after* every piece of state exists (the old code reset the metrics afterwards).
        self._load_checkpoint()

    # ---- optimiser helpers ---------------------------------------------------------------
    def _param_groups(self):
        decay, no_decay = [], []
        for n, p in self.model.named_parameters():
            if not p.requires_grad:
                continue
            if p.ndim <= 1 or n.endswith(".bias") or "emb" in n or "logit_scale" in n:
                no_decay.append(p)
            else:
                decay.append(p)
        return [{"params": decay, "weight_decay": self.cfg.weight_decay}, {"params": no_decay, "weight_decay": 0.0}]

    def _autocast(self):
        return torch.autocast(device_type=self.device.type, dtype=self.amp_dtype, enabled=self.use_amp)

    # ---- checkpoints ---------------------------------------------------------------------------
    @staticmethod
    def _atomic_save(obj, path: Path):
        tmp = path.with_name(path.name + ".tmp")
        torch.save(obj, tmp)
        os.replace(tmp, path)

    def _payload(self, epoch_complete: bool) -> Dict[str, Any]:
        return {
            "epoch": self.current_epoch,
            "epoch_complete": epoch_complete,
            "global_step": self.global_step,
            "model_state_dict": self.model.state_dict(),
            "ema_state_dict": self.ema.state_dict() if self.ema else None,
            "optimizer_state_dict": self.optimizer.state_dict(),
            "scheduler_state_dict": self.scheduler.state_dict(),
            "scaler_state_dict": self.scaler.state_dict(),
            "best_metric": self.best_metric,
            "history": self.history,
            "lr_history": self.lr_history,
            "config": self.cfg.to_dict(),
            "rng": {
                "python": random.getstate(),
                "numpy": np.random.get_state(),
                "torch": torch.get_rng_state(),
                "cuda": torch.cuda.get_rng_state_all() if torch.cuda.is_available() else None,
            },
        }

    def save_checkpoint(self, epoch_complete: bool = True, is_best: bool = False):
        payload = self._payload(epoch_complete)
        if epoch_complete:
            self._atomic_save(payload, self.checkpoint_dir / f"checkpoint_epoch_{self.current_epoch:04d}.pt")
            old = sorted(self.checkpoint_dir.glob("checkpoint_epoch_*.pt"))
            for p in old[: max(0, len(old) - self.cfg.keep_last_k)]:
                p.unlink(missing_ok=True)
        self._atomic_save(payload, self.checkpoint_dir / "checkpoint_latest.pt")
        if is_best:
            self._atomic_save(payload, self.checkpoint_dir / "checkpoint_best.pt")
            print(f"  -> new best model (metric = {self.best_metric:.4f})")
        print(f"Checkpoint saved at epoch {self.current_epoch} (complete={epoch_complete}, step={self.global_step})")

    def _load_checkpoint(self, path: Optional[Union[str, Path]] = None) -> bool:
        path = Path(path) if path else self.checkpoint_dir / "checkpoint_latest.pt"
        if not path.exists():
            print("No checkpoint found. Starting from scratch.")
            return False
        print(f"Loading checkpoint from {path}")
        ckpt = torch.load(path, map_location=self.device, weights_only=False)
        try:
            self.model.load_state_dict(ckpt["model_state_dict"])
        except RuntimeError as e:
            bad = path.with_name(path.stem + ".incompatible.pt")
            os.replace(path, bad)
            print(f"Checkpoint incompatible with the current architecture -> moved to {bad}. Starting from scratch.\n{e}")
            return False
        if self.ema is not None:
            if ckpt.get("ema_state_dict") is not None:
                self.ema.load_state_dict(ckpt["ema_state_dict"])
            else:
                self.ema = EMA(self.model, self.cfg.ema_decay)
        for obj, key in ((self.optimizer, "optimizer_state_dict"), (self.scheduler, "scheduler_state_dict"),
                         (self.scaler, "scaler_state_dict")):
            try:
                if ckpt.get(key) is not None:
                    obj.load_state_dict(ckpt[key])
            except Exception as e:  # noqa: BLE001
                print(f"  (could not restore {key}: {e})")
        self.global_step = int(ckpt.get("global_step", 0))
        self.best_metric = float(ckpt.get("best_metric", -float("inf")))
        self.history = ckpt.get("history", self.history) or {"epoch": []}
        self.lr_history = ckpt.get("lr_history", [])
        complete = ckpt.get("epoch_complete", True)
        self.current_epoch = int(ckpt["epoch"]) + (1 if complete else 0)
        rng = ckpt.get("rng") or {}
        try:
            random.setstate(rng["python"])
            np.random.set_state(rng["numpy"])
            torch.set_rng_state(rng["torch"].cpu())
            if rng.get("cuda") is not None and torch.cuda.is_available():
                torch.cuda.set_rng_state_all([s.cpu() for s in rng["cuda"]])
        except Exception:  # noqa: BLE001
            pass
        print(f"Resumed from epoch {ckpt['epoch']} ({'complete' if complete else 'interrupted'}), "
              f"global_step {self.global_step} -> continuing at epoch {self.current_epoch}")
        return True

    # ---- training ------------------------------------------------------------------------------
    def train_epoch(self) -> Dict[str, float]:
        cfg = self.cfg
        self.model.train()
        self.loss_fn.train()
        sums: Dict[str, float] = {}
        counts: Dict[str, int] = {}
        accum = max(1, cfg.grad_accum_steps)
        n_batches = len(self.train_loader)
        pbar = tqdm(self.train_loader, desc=f"Epoch {self.current_epoch} - Training", leave=False)
        self.optimizer.zero_grad(set_to_none=True)
        for i, batch in enumerate(pbar):
            x0 = batch["image"].to(self.device, non_blocking=True)
            with self._autocast():
                total, logs, extras = self.loss_fn(self.model, x0)
            if not torch.isfinite(total):
                print(f"  non-finite loss at step {self.global_step}; batch skipped")
                self.optimizer.zero_grad(set_to_none=True)
                continue
            self.scaler.scale(total / accum).backward()
            if (i + 1) % accum == 0 or (i + 1) == n_batches:
                self.scaler.unscale_(self.optimizer)
                logs["grad_norm"] = float(torch.nn.utils.clip_grad_norm_(self.model.parameters(), cfg.grad_clip))
                self.scaler.step(self.optimizer)
                self.scaler.update()
                self.optimizer.zero_grad(set_to_none=True)
                self.scheduler.step()
                self.global_step += 1
                if self.ema is not None:
                    self.ema.update(self.model, self.global_step)
                self.lr_history.append(self.optimizer.param_groups[0]["lr"])
                if cfg.viz_every > 0 and self.global_step % cfg.viz_every == 0:
                    self._visualize_training(extras, f"step_{self.global_step:07d}_epoch_{self.current_epoch:03d}")
            for k, v in logs.items():
                sums[k] = sums.get(k, 0.0) + v
                counts[k] = counts.get(k, 0) + 1
            pbar.set_postfix({"loss": f"{logs['total']:.4f}", "rec": f"{logs['rec']:.4f}", "psnr": f"{logs['psnr']:.2f}",
                              "lr": f"{self.optimizer.param_groups[0]['lr']:.2e}"})
        return {k: sums[k] / max(counts[k], 1) for k in sums}

    @torch.no_grad()
    def validate(self, model: ColdDiffusionModel, with_sampler: bool = False) -> Dict[str, float]:
        """Deterministic validation: fixed clocks (val_taus + one clock field), fixed seeds."""
        cfg = self.cfg
        was_training = model.training
        model.eval()
        self.loss_fn.eval()
        g = torch.Generator().manual_seed(cfg.seed + 777)
        sums: Dict[str, float] = {}
        counts: Dict[str, int] = {}
        taus: List[Any] = list(cfg.val_taus) + ["field"]
        n_val = len(self.val_loader) if cfg.val_max_batches <= 0 else min(len(self.val_loader), cfg.val_max_batches)
        for bi, batch in enumerate(tqdm(self.val_loader, desc=f"Epoch {self.current_epoch} - Validation", total=n_val, leave=False)):
            if bi >= n_val:
                break
            x0 = batch["image"].to(self.device).float()
            B, C, H, W = x0.shape
            for tv in taus:
                kind = model.sample_kind(B, self.device, g)
                if tv == "field":
                    tau = model.sample_tau(B, H, W, self.device, g, force_field=True)
                else:
                    tau = torch.full((B,), float(tv), device=self.device)
                with self._autocast():
                    _, logs, extras = self.loss_fn(model, x0, tau=tau, kind=kind, generator=g, rollout=True)
                logs["ssim"] = ssim(extras["x0_hat"], x0).mean().item()
                for k, v in logs.items():
                    sums[k] = sums.get(k, 0.0) + v * B
                    counts[k] = counts.get(k, 0) + B
        res = {k: sums[k] / max(counts[k], 1) for k in sums}
        if with_sampler:
            batch = next(iter(self.val_loader))
            x0 = batch["image"].to(self.device).float()
            B, C, H, W = x0.shape
            kind = model.sample_kind(B, self.device, g)
            tau = model.sample_tau(B, H, W, self.device, g, force_field=True)
            y, st = model.degradation.apply(x0, tau, kind, generator=g)
            observed = st["rank"] >= model.degradation.mask_ratio(tau)
            with self._autocast():
                r = model.restore(y, tau_obs=tau, kind=kind, steps=cfg.val_sampler_steps, sampler="srn", generator=g,
                                  observed=observed)
            res["sampler_psnr"] = psnr(r["output"], x0).mean().item()
        if was_training:
            model.train()
        return res

    def _append(self, key: str, value):
        lst = self.history.setdefault(key, [])
        while len(lst) < len(self.history["epoch"]) - 1:
            lst.append(None)
        lst.append(value)

    def _record(self, epoch, tr, va, ve):
        self.history["epoch"].append(epoch)
        for k, v in tr.items():
            self._append(f"train_{k}", v)
        for k, v in va.items():
            self._append(f"val_{k}", v)
        for k in ("psnr", "ssim", "sampler_psnr", "total"):
            if k in ve:
                self._append(f"val_ema_{k}", ve[k])
        self._append("lr", self.optimizer.param_groups[0]["lr"])
        n = len(self.history["epoch"])
        for k, lst in self.history.items():  # keep every column aligned with the epochs
            while len(lst) < n:
                lst.append(None)

    def train(self):
        cfg = self.cfg
        print(f"Starting training for {cfg.epochs} epochs (from epoch {self.current_epoch}) on {self.device} "
              f"| {self.steps_per_epoch} optimiser steps/epoch | AMP={self.use_amp} ({self.amp_dtype})")
        for epoch in range(self.current_epoch, cfg.epochs):
            self.current_epoch = epoch
            t0 = time.time()
            tr = self.train_epoch()
            do_val = ((epoch + 1) % max(1, cfg.val_every) == 0) or epoch == cfg.epochs - 1
            want_sampler = cfg.val_sampler_every > 0 and ((epoch + 1) % cfg.val_sampler_every == 0 or epoch == cfg.epochs - 1)
            va = self.validate(self.model, with_sampler=want_sampler and self.ema is None) if do_val else {}
            ve = self.validate(self.ema.model, with_sampler=want_sampler) if (do_val and self.ema is not None) else {}
            self._record(epoch, tr, va, ve)
            metric = ve.get("psnr", va.get("psnr", float("nan")))
            is_best = do_val and np.isfinite(metric) and metric > self.best_metric
            if is_best:
                self.best_metric = metric
            self.save_checkpoint(epoch_complete=True, is_best=is_best)
            self.plot_curves()
            self.save_history()
            print(f"\nEpoch {epoch} ({time.time() - t0:.0f}s) | train loss {tr.get('total', float('nan')):.5f} "
                  f"psnr {tr.get('psnr', float('nan')):.2f} | val loss {va.get('total', float('nan')):.5f} "
                  f"psnr {va.get('psnr', float('nan')):.2f} ssim {va.get('ssim', float('nan')):.4f} "
                  f"| EMA psnr {ve.get('psnr', float('nan')):.2f} sampler {ve.get('sampler_psnr', va.get('sampler_psnr', float('nan'))):.2f} "
                  f"| clock MAE {va.get('clock_mae', float('nan')):.4f} | lr {self.optimizer.param_groups[0]['lr']:.3e}")
        self.finalize()

    def finalize(self):
        """Fit the degraded prior (generation) and store it in every relevant checkpoint."""
        loader = DataLoader(self.train_dataset, batch_size=self.cfg.batch_size, shuffle=True, num_workers=0)
        if not self.model.fit_prior(loader, self.device):
            return
        if self.ema is not None:
            for name in PRIOR_BUFFERS:
                getattr(self.ema.model, name).copy_(getattr(self.model, name))
        for p in (self.checkpoint_dir / "checkpoint_best.pt", self.checkpoint_dir / "checkpoint_latest.pt"):
            if p.exists():
                ck = torch.load(p, map_location="cpu", weights_only=False)
                for key in ("model_state_dict", "ema_state_dict"):
                    if ck.get(key) is not None:
                        for name in PRIOR_BUFFERS:
                            ck[key][name] = getattr(self.model, name).detach().cpu().clone()
                self._atomic_save(ck, p)

