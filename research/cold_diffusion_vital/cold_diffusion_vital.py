# ------------------------------------ 5.1 generic layers ------------------------------------


class Mlp(nn.Module):
    """MLP as used in Vision Transformer, MLP-Mixer and related networks."""

    def __init__(self, in_features, hidden_features=None, out_features=None, act_layer=nn.GELU,
                 norm_layer=None, bias=True, drop=0.0, use_conv=False):
        super().__init__()
        out_features = out_features or in_features
        hidden_features = hidden_features or in_features
        bias = to_2tuple(bias)
        drop_probs = to_2tuple(drop)
        linear_layer = partial(nn.Conv2d, kernel_size=1) if use_conv else nn.Linear
        self.fc1 = linear_layer(in_features, hidden_features, bias=bias[0])
        self.act = act_layer()
        self.drop1 = nn.Dropout(drop_probs[0])
        self.norm = norm_layer(hidden_features) if norm_layer is not None else nn.Identity()
        self.fc2 = linear_layer(hidden_features, out_features, bias=bias[1])
        self.drop2 = nn.Dropout(drop_probs[1])

    def forward(self, x):
        x = self.drop1(self.act(self.fc1(x)))
        x = self.norm(x)
        return self.drop2(self.fc2(x))


class DropPath(nn.Module):
    """Drop paths (Stochastic Depth) per sample during training."""

    def __init__(self, drop_prob=0.0):
        super().__init__()
        self.drop_prob = drop_prob

    def forward(self, x):
        if self.drop_prob == 0.0 or not self.training:
            return x
        keep_prob = 1 - self.drop_prob
        shape = (x.shape[0],) + (1,) * (x.ndim - 1)
        random_tensor = (keep_prob + torch.rand(shape, dtype=x.dtype, device=x.device)).floor_()
        return x.div(keep_prob) * random_tensor


def bchw_to_bhwc(x: torch.Tensor) -> torch.Tensor:
    """Permutes a tensor from the shape (B, C, H, W) to (B, H, W, C)."""
    return x.permute(0, 2, 3, 1)


def bhwc_to_bchw(x: torch.Tensor) -> torch.Tensor:
    """Permutes a tensor from the shape (B, H, W, C) to (B, C, H, W)."""
    return x.permute(0, 3, 1, 2)


def window_partition(x, window_size: Tuple[int, int]):
    """Partition input feature (B, H, W, C) into non-overlapping windows."""
    B, H, W, C = x.shape
    wh, ww = window_size
    x = x.view(B, H // wh, wh, W // ww, ww, C)
    return x.permute(0, 1, 3, 2, 4, 5).contiguous().view(-1, wh, ww, C)


def window_reverse(windows, window_size: Tuple[int, int], img_size: Tuple[int, int]):
    """Reverse window partitioning."""
    H, W = img_size
    wh, ww = window_size
    C = windows.shape[-1]
    num_windows = (H // wh) * (W // ww)
    B = windows.shape[0] // num_windows
    x = windows.view(B, H // wh, W // ww, wh, ww, C)
    return x.permute(0, 1, 3, 2, 4, 5).contiguous().view(B, H, W, C)


# ------------------------------------ 5.2 Swin-V2 (CR) attention ------------------------------------


class WindowMultiHeadAttention(nn.Module):
    """Window-based multi-head cosine attention with log-spaced continuous position bias."""

    def __init__(self, dim: int, num_heads: int, window_size: Tuple[int, int], drop_attn: float = 0.0,
                 drop_proj: float = 0.0, meta_hidden_dim: int = 384):
        super().__init__()
        assert dim % num_heads == 0, f"Input features ({dim}) must be divisible by number of heads ({num_heads})."
        self.dim = dim
        self.head_dim = dim // num_heads
        self.window_size = to_2tuple(window_size)
        self.num_heads = num_heads
        self.qkv = nn.Linear(dim, dim * 3, bias=True)
        self.attn_drop = nn.Dropout(drop_attn)
        self.proj = nn.Linear(dim, dim, bias=True)
        self.proj_drop = nn.Dropout(drop_proj)
        self.meta_mlp = Mlp(2, hidden_features=meta_hidden_dim, out_features=num_heads, act_layer=nn.ReLU, drop=(0.125, 0.0))
        self.logit_scale = nn.Parameter(torch.log(10 * torch.ones(num_heads)))
        self.capture = False  # interpretability: keep the last attention maps
        self.last_attn: Optional[torch.Tensor] = None
        self._init_relative_position_encoding()

    def _init_relative_position_encoding(self) -> None:
        device = self.logit_scale.device
        coords = torch.stack(ndgrid(torch.arange(self.window_size[0], device=device),
                                    torch.arange(self.window_size[1], device=device)), dim=0).flatten(1)
        rel = (coords[:, :, None] - coords[:, None, :]).permute(1, 2, 0).reshape(-1, 2).float()
        rel_log = torch.sign(rel) * torch.log(1.0 + rel.abs())
        self.register_buffer("relative_coordinates_log", rel_log, persistent=False)
        self.register_buffer("relative_distance", rel.norm(dim=-1).view(self.window_area, self.window_area), persistent=False)

    @property
    def window_area(self):
        return self.window_size[0] * self.window_size[1]

    def _compute_relative_position_bias(self) -> torch.Tensor:
        bias = self.meta_mlp(self.relative_coordinates_log)
        return bias.transpose(1, 0).reshape(self.num_heads, self.window_area, self.window_area).unsqueeze(0)

    def forward(self, x: torch.Tensor, mask: Optional[torch.Tensor] = None) -> torch.Tensor:
        Bw, N, C = x.shape
        qkv = self.qkv(x).view(Bw, N, 3, self.num_heads, C // self.num_heads).permute(2, 0, 3, 1, 4)
        q, k, v = qkv.unbind(0)
        attn = F.normalize(q, dim=-1) @ F.normalize(k, dim=-1).transpose(-2, -1)
        logit_scale = torch.clamp(self.logit_scale.reshape(1, self.num_heads, 1, 1), max=math.log(1.0 / 0.01)).exp()
        attn = attn * logit_scale + self._compute_relative_position_bias()
        if mask is not None:
            nW = mask.shape[0]
            attn = attn.view(Bw // nW, nW, self.num_heads, N, N) + mask.unsqueeze(1).unsqueeze(0)
            attn = attn.view(-1, self.num_heads, N, N)
        attn = attn.softmax(dim=-1)
        if self.capture:
            self.last_attn = attn.detach().float()
        attn = self.attn_drop(attn)
        x = (attn @ v).transpose(1, 2).reshape(Bw, N, C)
        return self.proj_drop(self.proj(x))


class SwinTransformerBlock(nn.Module):
    """Swin-V2 (res-post-norm) block. Pads *then* rolls; attention masks are cached per size."""

    def __init__(self, dim: int, num_heads: int, window_size, shift_size=0, mlp_ratio: float = 4.0,
                 init_values: Optional[float] = 0.0, proj_drop: float = 0.0, drop_attn: float = 0.0,
                 drop_path: float = 0.0, extra_norm: bool = False, norm_layer=nn.LayerNorm):
        super().__init__()
        self.dim = dim
        self.window_size = to_2tuple(window_size)
        shift = to_2tuple(shift_size)
        self.shift_size = (self.window_size[0] // 2, self.window_size[1] // 2) if any(shift) else (0, 0)
        self.window_area = self.window_size[0] * self.window_size[1]
        self.init_values = init_values
        self.norm1 = norm_layer(dim)
        self.attn = WindowMultiHeadAttention(dim, num_heads, self.window_size, drop_attn, proj_drop)
        self.drop_path1 = DropPath(drop_path) if drop_path > 0.0 else nn.Identity()
        self.norm2 = norm_layer(dim)
        self.mlp = Mlp(dim, hidden_features=int(dim * mlp_ratio), out_features=dim, drop=proj_drop)
        self.drop_path2 = DropPath(drop_path) if drop_path > 0.0 else nn.Identity()
        self.norm3 = norm_layer(dim) if extra_norm else nn.Identity()
        self._mask_cache: Dict[Tuple[int, int, str], Optional[torch.Tensor]] = {}
        if self.init_values is not None:  # layer-scale-like zero init of the residual branches
            nn.init.constant_(self.norm1.weight, self.init_values)
            nn.init.constant_(self.norm2.weight, self.init_values)

    def _attention_mask(self, Hp: int, Wp: int, device) -> Optional[torch.Tensor]:
        if not any(self.shift_size):
            return None
        key = (Hp, Wp, str(device))
        if key not in self._mask_cache:
            wh, ww = self.window_size
            sh, sw = self.shift_size
            img_mask = torch.zeros((1, Hp, Wp, 1), device=device)
            cnt = 0
            for hs in (slice(0, -wh), slice(-wh, -sh), slice(-sh, None)):
                for ws in (slice(0, -ww), slice(-ww, -sw), slice(-sw, None)):
                    img_mask[:, hs, ws, :] = cnt
                    cnt += 1
            mw = window_partition(img_mask, self.window_size).view(-1, self.window_area)
            m = mw.unsqueeze(1) - mw.unsqueeze(2)
            self._mask_cache[key] = m.masked_fill(m != 0, -100.0).masked_fill(m == 0, 0.0)
        return self._mask_cache[key]

    def _shifted_window_attention(self, x):
        B, H, W, C = x.shape
        wh, ww = self.window_size
        pad_h, pad_w = (wh - H % wh) % wh, (ww - W % ww) % ww
        x = F.pad(x, (0, 0, 0, pad_w, 0, pad_h))
        Hp, Wp = H + pad_h, W + pad_w
        sh, sw = self.shift_size
        if sh or sw:
            x = torch.roll(x, shifts=(-sh, -sw), dims=(1, 2))
        xw = window_partition(x, self.window_size).view(-1, self.window_area, C)
        aw = self.attn(xw, mask=self._attention_mask(Hp, Wp, x.device)).view(-1, wh, ww, C)
        x = window_reverse(aw, self.window_size, (Hp, Wp))
        if sh or sw:
            x = torch.roll(x, shifts=(sh, sw), dims=(1, 2))
        return x[:, :H, :W, :].contiguous()

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        B, H, W, C = x.shape
        x = x + self.drop_path1(self.norm1(self._shifted_window_attention(x)))
        x = x.reshape(B, -1, C)
        x = x + self.drop_path2(self.norm2(self.mlp(x)))
        x = self.norm3(x)
        return x.reshape(B, H, W, C)


# ------------------------------------ 5.3 clock conditioning  [N1] ------------------------------------


class Cond:
    """Conditioning bundle passed through the network: global features, per-pixel clock
    embedding (lazily pooled to every resolution) and the mean blur std (pixels)."""

    def __init__(self, feats: torch.Tensor, cmap: Optional[torch.Tensor], sigma_bar: torch.Tensor):
        self.feats, self.cmap, self.sigma_bar = feats, cmap, sigma_bar
        self._cache: Dict[Tuple[int, int], torch.Tensor] = {}

    def cmap_at(self, h: int, w: int) -> Optional[torch.Tensor]:
        if self.cmap is None:
            return None
        if (h, w) not in self._cache:
            self._cache[(h, w)] = self.cmap if tuple(self.cmap.shape[-2:]) == (h, w) else F.adaptive_avg_pool2d(self.cmap, (h, w))
        return self._cache[(h, w)]


class TimePosEmbedding(nn.Module):
    """Sinusoidal embedding. tau in [0, 1] is scaled by T (the original fed t~1e-6)."""

    def __init__(self, dim, scale: float = 1000.0):
        super().__init__()
        self.dim = dim
        self.scale = scale

    def forward(self, t):
        t = t.float() * self.scale
        half = self.dim // 2
        emb = math.log(10000) / (half - 1)
        emb = torch.exp(torch.arange(half, device=t.device) * -emb)
        emb = t[:, None] * emb[None, :]
        return torch.cat((emb.sin(), emb.cos()), dim=-1)


class ClockEmbedding(nn.Module):
    """Per-pixel Fourier embedding of the clock field tau(x) -> (B, E, H, W)."""

    def __init__(self, out_dim: int = 32, n_freq: int = 6):
        super().__init__()
        self.register_buffer("freqs", (2.0 ** torch.arange(n_freq)).float() * math.pi, persistent=False)
        self.net = nn.Sequential(nn.Conv2d(2 * n_freq + 1, out_dim, 1), nn.SiLU(), nn.Conv2d(out_dim, out_dim, 1))

    def forward(self, tau):
        ang = tau * self.freqs.view(1, -1, 1, 1)
        return self.net(torch.cat([tau, ang.sin(), ang.cos()], 1))


class ClockModulatedNorm2d(nn.Module):
    """
    Clock-Modulated Normalisation (successor of ConditionalNorm2d):
        out = GN(x) * (1 + g_global(f) + g_spatial(E(tau)))  +  b_global(f) + b_spatial(E(tau))
    Zero-initialised -> starts as plain GroupNorm (the old version started from random scales).
    """

    def __init__(self, channels, num_features, clock_dim: int = 0):
        super().__init__()
        self.channels = channels
        self.norm = nn.GroupNorm(num_groups(channels), channels, affine=False, eps=1e-4)
        self.fc = nn.Linear(num_features, 2 * channels)
        nn.init.zeros_(self.fc.weight)
        nn.init.zeros_(self.fc.bias)
        self.spatial = nn.Conv2d(clock_dim, 2 * channels, 1) if clock_dim > 0 else None
        if self.spatial is not None:
            nn.init.zeros_(self.spatial.weight)
            nn.init.zeros_(self.spatial.bias)

    def forward(self, x, cond: Cond):
        out = self.norm(x)
        g, b = self.fc(cond.feats)[:, :, None, None].chunk(2, 1)
        if self.spatial is not None and cond.cmap is not None:
            gs, bs = self.spatial(cond.cmap_at(*x.shape[-2:])).chunk(2, 1)
            g, b = g + gs, b + bs
        return out * (1 + g) + b


# ------------------------------------ 5.4 attention / conv blocks ------------------------------------


class ChannelAttention(nn.Module):
    def __init__(self, channels, reduction=16):
        super().__init__()
        hidden = max(1, channels // reduction)
        self.avg_pool = nn.AdaptiveAvgPool2d(1)
        self.max_pool = nn.AdaptiveMaxPool2d(1)
        self.fc = nn.Sequential(nn.Conv2d(channels, hidden, 1), nn.ReLU(inplace=True), nn.Conv2d(hidden, channels, 1))
        self.sigmoid = nn.Sigmoid()

    def forward(self, x):
        return self.sigmoid(self.fc(self.avg_pool(x)) + self.fc(self.max_pool(x))) * x


class SpatialAttention(nn.Module):
    def __init__(self, kernel_size=7):
        super().__init__()
        self.conv = nn.Conv2d(2, 1, kernel_size=kernel_size, padding=kernel_size // 2)
        self.sigmoid = nn.Sigmoid()

    def forward(self, x):
        avg_out = torch.mean(x, dim=1, keepdim=True)
        max_out, _ = torch.max(x, dim=1, keepdim=True)
        return x * self.sigmoid(self.conv(torch.cat([avg_out, max_out], dim=1)))


class BAM(nn.Module):
    def __init__(self, channels, reduction=16, kernel_size=7):
        super().__init__()
        self.cam = ChannelAttention(channels, reduction)
        self.sam = SpatialAttention(kernel_size)

    def forward(self, x):
        return self.cam(self.sam(x) + x) + x


class SqueezeExcitation(nn.Module):
    def __init__(self, channels):
        super().__init__()
        hidden = max(1, channels // 8)
        self.squeeze = nn.AdaptiveAvgPool2d(1)
        self.excitation = nn.Sequential(nn.Linear(channels, hidden), nn.ReLU(inplace=True), nn.Linear(hidden, channels), nn.Sigmoid())

    def forward(self, x):
        b, c = x.shape[:2]
        excited = self.excitation(self.squeeze(x).view(b, c)).view(b, c, 1, 1)
        return x * excited + x


class Stem(nn.Module):
    """GroupNorm instead of BatchNorm (tiny batches + train/eval statistics mismatch)."""

    def __init__(self, in_channels, latent_channels):
        super().__init__()
        mid = max(8, latent_channels // 2)
        self.conv1 = nn.Conv2d(in_channels, mid, kernel_size=3, stride=1, padding=1)
        self.norm1 = nn.GroupNorm(num_groups(mid), mid)
        self.conv2 = nn.Conv2d(mid, latent_channels, kernel_size=3, stride=1, padding=1)
        self.norm2 = nn.GroupNorm(num_groups(latent_channels), latent_channels)
        self.act = nn.ReLU()

    def forward(self, x):
        x = self.act(self.norm1(self.conv1(x)))
        return self.act(self.norm2(self.conv2(x)))


class ResBlock(nn.Module):
    def __init__(self, channel_in, channel_out, kernel_size=3, num_features=128, clock_dim=32):
        super().__init__()
        self.norm1 = ClockModulatedNorm2d(channel_in, num_features, clock_dim)
        self.conv1 = nn.Conv2d(channel_in, channel_in, kernel_size, 1, kernel_size // 2)
        self.norm2 = ClockModulatedNorm2d(channel_in, num_features, clock_dim)
        self.conv2 = nn.Conv2d(channel_in, channel_out, kernel_size, 1, kernel_size // 2)
        self.conv3 = nn.Conv2d(channel_in, channel_out, 1) if channel_in != channel_out else None
        self.act_fnc = nn.ELU()

    def forward(self, x_in, cond: Cond):
        x = self.act_fnc(self.norm1(x_in, cond))
        skip = self.conv3(x) if self.conv3 is not None else x_in
        x = self.act_fnc(self.norm2(self.conv1(x), cond))
        return self.conv2(x) + skip


class DownBlock(nn.Module):
    def __init__(self, in_channels, out_channels, kernel_size=3, num_features=128, clock_dim=32):
        super().__init__()
        self.norm1 = ClockModulatedNorm2d(in_channels, num_features, clock_dim)
        self.conv1 = nn.Conv2d(in_channels, out_channels, kernel_size, 2, kernel_size // 2)
        self.norm2 = ClockModulatedNorm2d(out_channels, num_features, clock_dim)
        self.conv2 = nn.Conv2d(out_channels, out_channels, kernel_size, 1, kernel_size // 2)
        self.conv3 = nn.Conv2d(in_channels, out_channels, kernel_size, 2, kernel_size // 2)
        self.act_fnc = nn.LeakyReLU(0.2)

    def forward(self, x, cond):
        x = self.act_fnc(self.norm1(x, cond))
        s = self.conv3(x)
        x = self.act_fnc(self.norm2(self.conv1(x), cond))
        return self.conv2(x) + s


class UpBlock(nn.Module):
    def __init__(self, in_channels, out_channels, kernel_size=3, scale_factor=2, num_features=128, clock_dim=32):
        super().__init__()
        self.norm1 = ClockModulatedNorm2d(in_channels, num_features, clock_dim)
        self.conv1 = nn.Conv2d(in_channels, in_channels, kernel_size, 1, kernel_size // 2)
        self.norm2 = ClockModulatedNorm2d(in_channels, num_features, clock_dim)
        self.conv2 = nn.Conv2d(in_channels, out_channels, kernel_size, 1, kernel_size // 2)
        self.conv3 = nn.Conv2d(in_channels, out_channels, kernel_size, 1, kernel_size // 2)
        self.up_nn = nn.Upsample(scale_factor=scale_factor, mode="bicubic", align_corners=False)
        self.act_f = nn.LeakyReLU(0.2)

    def forward(self, x, cond):
        x = self.up_nn(self.act_f(self.norm1(x, cond)))
        s = self.conv3(x)
        x = self.act_f(self.norm2(self.conv1(x), cond))
        return self.conv2(x) + s


class DenseBlock(nn.Module):
    def __init__(self, in_channels, growth_rate, kernel_size=3, num_features=128, clock_dim=32, num_layers=4):
        super().__init__()
        self.layers = nn.ModuleList([
            ResBlock(in_channels + growth_rate * i, growth_rate, kernel_size, num_features, clock_dim) for i in range(num_layers)
        ])

    def forward(self, x, cond):
        feats = [x]
        for layer in self.layers:
            feats.append(layer(torch.cat(feats, dim=1), cond))
        return torch.cat(feats, dim=1)


class TransitionBlock(nn.Module):
    def __init__(self, in_channels, out_channels):
        super().__init__()
        self.conv = nn.Sequential(nn.GroupNorm(num_groups(in_channels), in_channels), nn.ReLU(inplace=True),
                                  nn.Conv2d(in_channels, out_channels, kernel_size=1))

    def forward(self, x):
        return self.conv(x)


class DCNet(nn.Module):
    def __init__(self, in_channels, growth_rate=32, kernel_size=3, num_features=128, clock_dim=32, num_layers=4):
        super().__init__()
        self.dense_block = DenseBlock(in_channels, growth_rate, kernel_size, num_features, clock_dim, num_layers)
        self.trans_block = TransitionBlock(in_channels + growth_rate * num_layers, in_channels)

    def forward(self, x, cond):
        return self.trans_block(self.dense_block(x, cond)) + x


class EncoderBlock(nn.Module):
    def __init__(self, in_channels, out_channels, kernel_size=3, num_features=128, clock_dim=32, growth_rate=32, num_layers=2):
        super().__init__()
        self.se = SqueezeExcitation(in_channels)
        self.down = DownBlock(in_channels, out_channels, kernel_size, num_features, clock_dim)
        self.cond = DCNet(out_channels, growth_rate, kernel_size, num_features, clock_dim, num_layers)
        self.res = ResBlock(out_channels, out_channels, 3, num_features, clock_dim)

    def forward(self, x, cond):
        x = self.down(self.se(x), cond)
        x = self.cond(x, cond)
        return self.res(x, cond)


class Encoder(nn.Module):
    def __init__(self, base_channels, num_features=128, clock_dim=32):
        super().__init__()
        b = base_channels
        self.block1 = EncoderBlock(b, b * 2, 5, num_features, clock_dim)  # H/2
        self.block2 = EncoderBlock(b * 2, b * 4, 3, num_features, clock_dim)  # H/4
        self.block3 = EncoderBlock(b * 4, b * 8, 5, num_features, clock_dim)  # H/8
        self.convo = ResBlock(b * 8, num_features, 3, num_features, clock_dim)

    def forward(self, x, cond):
        s1 = self.block1(x, cond)
        s2 = self.block2(s1, cond)
        s3 = self.block3(s2, cond)
        return self.convo(s3, cond), {"block1": s1, "block2": s2, "block3": s3}


class DecoderUpBlock(nn.Module):
    def __init__(self, in_channels, out_channels, kernel_size=3, num_features=128, clock_dim=32):
        super().__init__()
        self.bam = BAM(in_channels)
        self.up = UpBlock(in_channels, out_channels, kernel_size, 2, num_features, clock_dim)

    def forward(self, x, cond):
        return self.up(self.bam(x), cond)


class DecoderConvBlock(nn.Module):
    def __init__(self, in_channels, out_channels, kernel_size=3, num_features=128, clock_dim=32):
        super().__init__()
        self.se = SqueezeExcitation(in_channels)
        self.res = ResBlock(in_channels, out_channels, kernel_size, num_features, clock_dim)

    def forward(self, x, cond):
        return self.res(self.se(x), cond)


# ------------------------------------ 5.5 Clock-Aware Spectral Gate  [N3] ------------------------------------


class ClockAwareSpectralGate(nn.Module):
    """
    Feature-space inverse-heat filter conditioned on the clock:
        log G_c(w) = ceil_c * tanh(a_c * s_f^2 |w|^2 / (2 ceil_c))  +  tanh(MLP(|w|, 1 - K(w), heat))
    where s_f = sigma_bar / downscale is the blur std *at this feature resolution* and K the
    heat transfer function. The first term is a bounded, partial inversion of the physical
    blur (a_c in (0, 1) learned per channel); the second is a learned residual spectral
    response. Output is spatially gated by the clock embedding and added residually
    (zero-initialised projection -> identity at init).
    """

    def __init__(self, channels: int, clock_dim: int, downscale: int, hidden: int = 32, init_log_ceiling: float = 1.5):
        super().__init__()
        self.downscale = downscale
        self.alpha = nn.Parameter(torch.full((channels,), -1.0))
        self.ceiling = nn.Parameter(torch.full((channels,), init_log_ceiling))
        self.freq_mlp = nn.Sequential(nn.Linear(3, hidden), nn.SiLU(), nn.Linear(hidden, channels))
        nn.init.zeros_(self.freq_mlp[-1].weight)
        nn.init.zeros_(self.freq_mlp[-1].bias)
        self.proj = nn.Conv2d(channels, channels, 1)
        nn.init.zeros_(self.proj.weight)
        nn.init.zeros_(self.proj.bias)
        self.gate = nn.Conv2d(clock_dim, channels, 1)

    def log_gain(self, sigma_feat: torch.Tensor, h: int, w: int) -> torch.Tensor:
        w2 = HeatKernel.omega_sq(h, w, sigma_feat.device)
        heat = 0.5 * sigma_feat.float().view(-1, 1, 1, 1) ** 2 * w2  # (B, 1, 2h, w+1)
        a = torch.sigmoid(self.alpha).view(1, -1, 1, 1)
        ceil = F.softplus(self.ceiling).view(1, -1, 1, 1)
        phys = ceil * torch.tanh(a * heat / ceil)  # smooth, bounded partial inverse heat
        feat = torch.stack([w2.sqrt().expand_as(heat[:, 0]) / math.pi, 1 - torch.exp(-heat[:, 0]),
                            torch.tanh(heat[:, 0] / 4)], dim=-1)
        learned = torch.tanh(self.freq_mlp(feat)).permute(0, 3, 1, 2)
        return phys + learned

    def forward(self, x, cond: Cond):
        B, C, h, w = x.shape
        with autocast_off(x.device.type):
            sig = cond.sigma_bar.float() / self.downscale
            y = HeatKernel.inverse(HeatKernel.spectrum(x.float()) * torch.exp(self.log_gain(sig, h, w).float()), h, w)
        y = self.proj(y.to(x.dtype))
        cm_ = cond.cmap_at(h, w)
        g = torch.sigmoid(self.gate(cm_)) if cm_ is not None else 0.5
        return x + g * y


# ------------------------------------ 5.6 bottleneck / decoder / ViTAL ------------------------------------


class ColdDiffusionBlock(nn.Module):
    """Cold-diffusion bottleneck: clock-modulated norm -> Swin blocks -> spectral gate -> norm."""

    def __init__(self, dim, num_features, clock_dim, num_heads, window_size, mlp_ratio=4.0, num_blocks=2,
                 use_gate=True, downscale=8, drop_path=0.1, drop=0.0):
        super().__init__()
        self.window_size = to_2tuple(window_size)
        self.norm = ClockModulatedNorm2d(dim, num_features, clock_dim)
        self.swin_blocks = nn.ModuleList([
            SwinTransformerBlock(dim=dim, num_heads=num_heads, window_size=window_size,
                                 shift_size=0 if i % 2 == 0 else window_size // 2,  # W-MSA then SW-MSA
                                 mlp_ratio=mlp_ratio, proj_drop=drop, drop_attn=drop, drop_path=drop_path)
            for i in range(num_blocks)
        ])
        self.gate = ClockAwareSpectralGate(dim, clock_dim, downscale) if use_gate else None
        self.out_norm = ClockModulatedNorm2d(dim, num_features, clock_dim)

    def forward(self, z, cond):
        z = self.norm(z, cond)
        z = bchw_to_bhwc(z)
        for blk in self.swin_blocks:
            z = blk(z)
        z = bhwc_to_bchw(z).contiguous()
        if self.gate is not None:
            z = self.gate(z, cond)
        return self.out_norm(z, cond)


def _match(skip: torch.Tensor, ref: torch.Tensor) -> torch.Tensor:
    if skip.shape[-2:] != ref.shape[-2:]:
        skip = F.interpolate(skip, size=ref.shape[-2:], mode="bilinear", align_corners=False)
    return skip


class Decoder(nn.Module):
    """U-Net decoder with *resolution-aligned* skips (stem H, block1 H/2, block2 H/4, block3 H/8)."""

    def __init__(self, num_features, base_channels, out_channels, clock_dim=32, use_gate=True):
        super().__init__()
        b, nf, cd = base_channels, num_features, clock_dim
        self.init_proj = nn.Conv2d(nf, b * 8, kernel_size=1)
        self.block_in = ResBlock(b * 8, b * 8, 3, nf, cd)
        self.fuse4 = DecoderConvBlock(b * 8 + b * 8, b * 8, 3, nf, cd)
        self.up_block3 = DecoderUpBlock(b * 8, b * 4, 3, nf, cd)
        self.up_conv3 = DecoderConvBlock(b * 4 + b * 4, b * 4, 3, nf, cd)
        self.gate3 = ClockAwareSpectralGate(b * 4, cd, downscale=4) if use_gate else None
        self.up_block2 = DecoderUpBlock(b * 4, b * 2, 5, nf, cd)
        self.up_conv2 = DecoderConvBlock(b * 2 + b * 2, b * 2, 5, nf, cd)
        self.up_block1 = DecoderUpBlock(b * 2, b, 3, nf, cd)
        self.up_conv1 = DecoderConvBlock(b + b, b, 3, nf, cd)
        self.refine = DCNet(b, growth_rate=16, kernel_size=5, num_features=nf, clock_dim=cd, num_layers=4)
        self.output = nn.Conv2d(b, out_channels, 3, 1, 1)
        nn.init.zeros_(self.output.weight)  # x0_hat = x_t at initialisation (residual form)
        nn.init.zeros_(self.output.bias)

    def forward(self, x, skips, cond):
        x = self.block_in(self.init_proj(x), cond)
        x = self.fuse4(torch.cat([x, _match(skips["block3"], x)], 1), cond)
        x = self.up_block3(x, cond)
        x = self.up_conv3(torch.cat([x, _match(skips["block2"], x)], 1), cond)
        if self.gate3 is not None:
            x = self.gate3(x, cond)
        x = self.up_block2(x, cond)
        x = self.up_conv2(torch.cat([x, _match(skips["block1"], x)], 1), cond)
        x = self.up_block1(x, cond)
        x = self.up_conv1(torch.cat([x, _match(skips["stem"], x)], 1), cond)
        x = self.refine(x, cond)
        return self.output(x)


class ViTAL(nn.Module):
    """
    ViTAL restoration backbone (no VQ) conditioned on a per-pixel clock field.
    Inputs : x_t, tau(x), sigma_bar, degradation type, optional self-conditioning x0 estimate.
    Outputs: x0_hat (residual form) and a per-pixel Laplace log-scale (aleatoric uncertainty).
    """

    def __init__(self, in_channels=3, dim=48, num_heads=8, window_size=8, num_features=128, clock_dim=32,
                 swin_blocks=2, self_condition=True, predict_uncertainty=True, use_spectral_gate=True,
                 with_residual=True, n_types=len(KINDS), drop_path=0.1, drop=0.0, num_timesteps=1000):
        super().__init__()
        self.in_channels = in_channels
        self.self_condition = self_condition
        self.predict_uncertainty = predict_uncertainty
        self.with_residual = with_residual
        nf = num_features
        self.time_mlp = nn.Sequential(TimePosEmbedding(nf, scale=num_timesteps), nn.Linear(nf, 2 * nf), nn.GELU(),
                                      nn.Linear(2 * nf, nf), nn.GELU())
        self.spread_mlp = nn.Sequential(nn.Linear(1, nf), nn.GELU(), nn.Linear(nf, nf))
        self.type_emb = nn.Embedding(n_types, nf)
        nn.init.zeros_(self.type_emb.weight)
        self.clock_embed = ClockEmbedding(clock_dim)
        stem_in = in_channels * (2 if self_condition else 1) + 1
        self.inp = Stem(stem_in, dim)
        self.enc = Encoder(dim, nf, clock_dim)
        self.trans = ColdDiffusionBlock(nf, nf, clock_dim, num_heads, window_size, 4.0, swin_blocks,
                                        use_spectral_gate, downscale=8, drop_path=drop_path, drop=drop)
        self.dec = Decoder(nf, dim, in_channels * (2 if predict_uncertainty else 1), clock_dim, use_spectral_gate)

    @classmethod
    def from_config(cls, cfg: Config) -> "ViTAL":
        return cls(in_channels=cfg.in_channels, dim=cfg.dim, num_heads=cfg.num_heads, window_size=cfg.window_size,
                   num_features=cfg.num_features, clock_dim=cfg.clock_embed_dim, swin_blocks=cfg.swin_blocks,
                   self_condition=cfg.self_condition, predict_uncertainty=cfg.predict_uncertainty,
                   use_spectral_gate=cfg.use_spectral_gate, with_residual=cfg.with_residual,
                   drop_path=cfg.swin_drop_path, drop=cfg.swin_drop, num_timesteps=cfg.num_timesteps)

    def forward(self, x, tau_map, sigma_bar, kind=None, self_cond=None):
        flat = tau_map.flatten(1).float()
        feats = self.time_mlp(flat.mean(1)) + self.spread_mlp(flat.std(1, unbiased=False).unsqueeze(-1))
        if kind is not None:
            feats = feats + self.type_emb(kind)
        cond = Cond(feats, self.clock_embed(tau_map.float()), sigma_bar)
        parts = [x]
        if self.self_condition:
            parts.append(self_cond if self_cond is not None else torch.zeros_like(x))
        parts.append(tau_map.to(x.dtype) * 2 - 1)
        h0 = self.inp(torch.cat(parts, 1))
        latent, skips = self.enc(h0, cond)
        skips["stem"] = h0
        latent = self.trans(latent, cond)
        out = self.dec(latent, skips, cond).float()
        C = self.in_channels
        x0 = x.float() + out[:, :C] if self.with_residual else out[:, :C]
        log_scale = out[:, C:2 * C].clamp(-7.0, 2.0) if self.predict_uncertainty else None
        return {"x0": x0, "log_scale": log_scale}


# ------------------------------------ 5.7 Spectral Clock Estimator  [N1] ------------------------------------


class _DilatedResBlock(nn.Module):
    def __init__(self, c, d):
        super().__init__()
        self.conv1 = nn.Conv2d(c, c, 3, 1, d, dilation=d)
        self.n1 = nn.GroupNorm(num_groups(c), c)
        self.conv2 = nn.Conv2d(c, c, 3, 1, 1)
        self.n2 = nn.GroupNorm(num_groups(c), c)

    def forward(self, x):
        return x + self.n2(self.conv2(F.silu(self.n1(self.conv1(x)))))


class SpectralClockEstimator(nn.Module):
    """
    Blind estimator of the per-pixel clock tau(x) (and of the degradation type).

    Physics features: band-pass (difference-of-heat) energies of the luminance at scales
    s_j and their log-ratios. Under Gaussian blur sigma, band j is attenuated by roughly
    exp(-sigma^2 w_j^2), so log E_j - log E_{j+1} is (locally) *linear in sigma^2*: the
    clock can be read off the spectrum slope. A small dilated CNN turns these into
    (mu, log-scale) of a Laplace distribution over tau; flat regions (no spectral evidence)
    get a large scale and are filled by confidence-weighted normalised convolution.
    """

    def __init__(self, in_channels=3, hidden=32, bands=(0.5, 1.0, 2.0, 4.0, 8.0), n_types=len(KINDS), window=15):
        super().__init__()
        self.bands = tuple(float(b) for b in bands)
        self.window = int(window) | 1
        J = len(self.bands)
        c_in = in_channels + 2 * J - 1
        h = hidden
        self.body = nn.Sequential(
            nn.Conv2d(c_in, h, 3, 1, 1), nn.GroupNorm(num_groups(h), h), nn.SiLU(),
            nn.Conv2d(h, h, 3, 2, 1), nn.GroupNorm(num_groups(h), h), nn.SiLU(),
            nn.Conv2d(h, 2 * h, 3, 2, 1), nn.GroupNorm(num_groups(2 * h), 2 * h), nn.SiLU(),
            _DilatedResBlock(2 * h, 1), _DilatedResBlock(2 * h, 2), _DilatedResBlock(2 * h, 4), _DilatedResBlock(2 * h, 8),
        )
        self.head = nn.Conv2d(2 * h, 2, 3, 1, 1)
        self.type_head = nn.Sequential(nn.AdaptiveAvgPool2d(1), nn.Flatten(), nn.Linear(2 * h, h), nn.SiLU(), nn.Linear(h, n_types))

    def physics_features(self, x: torch.Tensor) -> torch.Tensor:
        with autocast_off(x.device.type):
            lum = x.float().mean(1, keepdim=True)
            h, w = lum.shape[-2:]
            L = HeatKernel.spectrum(lum)
            levels = [lum] + [HeatKernel.inverse(L * HeatKernel.transfer(s, h, w, x.device), h, w) for s in self.bands]
            energies = []
            for j in range(len(self.bands)):
                band = levels[j] - levels[j + 1]
                e = F.avg_pool2d(band ** 2, self.window, 1, self.window // 2, count_include_pad=False)
                energies.append(torch.log(e + 1e-6))
            slopes = [energies[j] - energies[j + 1] for j in range(len(energies) - 1)]
            return torch.cat([(e + 7.0) / 4.0 for e in energies] + slopes, 1)

    def forward(self, x: torch.Tensor) -> Dict[str, torch.Tensor]:
        H, W = x.shape[-2:]
        phys = self.physics_features(x)
        h = self.body(torch.cat([x.float(), phys], 1))
        out = F.interpolate(self.head(h).float(), size=(H, W), mode="bilinear", align_corners=False)
        return {"tau_mu": torch.sigmoid(out[:, :1]), "tau_logscale": out[:, 1:2].clamp(-7.0, 2.0),
                "type_logits": self.type_head(h).float(), "physics": phys}

    @staticmethod
    def smooth(tau_mu: torch.Tensor, logscale: torch.Tensor, sigma: float) -> torch.Tensor:
        """Confidence-propagated clock: blur(c * mu) / blur(c), c = 1/scale (normalised convolution)."""
        conf = torch.exp(-logscale.float().clamp(-6, 4))
        num = HeatKernel.blur(tau_mu.float() * conf, sigma)
        den = HeatKernel.blur(conf, sigma)
        return (num / den.clamp_min(1e-6)).clamp(0, 1)


# ------------------------------------ 5.8 Cold diffusion wrapper ------------------------------------


class ColdDiffusionModel(nn.Module):
    """
    Clock-Field Cold Diffusion around the ViTAL backbone.

        forward process  : x_tau = D(x0, tau(x))                 (deterministic, continuous tau)
        network          : x0_hat, log b = R(x_tau, tau, kind, x0_prev)
        samplers         : 'direct' (1 step), 'naive' (Alg. 1), 'improved' (Alg. 2),
                           'srn' (Alg. 2 + spectral range-null anchoring, [N2])
        blind mode       : tau_obs(x) from the Spectral Clock Estimator     [N1]
        generation       : degraded-prior bank + srn sampler                [N8]
    """

    def __init__(self, model: ViTAL, cfg: Config):
        super().__init__()
        self.model = model
        self.cfg = cfg
        self.degradation_type = cfg.degradation_type
        self.num_timesteps = cfg.num_timesteps
        self.schedule_type = cfg.schedule_type
        self.degradation = ColdDegradation(cfg)
        self.clock_estimator = SpectralClockEstimator(cfg.in_channels, cfg.clock_hidden, cfg.clock_bands, len(KINDS), cfg.clock_window)
        self.pad_multiple = 8
        D = cfg.in_channels * cfg.prior_res ** 2
        self.register_buffer("prior_mean", torch.zeros(D))
        self.register_buffer("prior_factor", torch.zeros(D, D))
        self.register_buffer("prior_ready", torch.zeros(1))

    # ---- sampling of training conditions -------------------------------------------------
    def sample_kind(self, B: int, device, generator=None) -> torch.Tensor:
        if self.cfg.degradation_type == "mixed":
            return (_rand((B,), device, generator) * len(KINDS)).long().clamp(max=len(KINDS) - 1)
        return torch.full((B,), KINDS.index(self.cfg.degradation_type), dtype=torch.long, device=device)

    def _random_field(self, n, H, W, device, generator=None) -> torch.Tensor:
        """Smooth ('defocus-like') or layered ('foreground/background') field in [-1, 1]."""
        lo_r, hi_r = self.cfg.field_grid
        r = int(lo_r + _rand((1,), "cpu", generator).item() * (hi_r - lo_r + 1))
        r = int(min(max(r, 2), max(hi_r, 2)))
        f = F.interpolate(_randn((n, 1, r, r), device, generator), size=(H, W), mode="bicubic", align_corners=False)
        layered = _rand((n, 1, 1, 1), device, generator) < 0.5
        sharp = 2 + 6 * _rand((n, 1, 1, 1), device, generator)
        f = torch.where(layered, torch.tanh(sharp * f), f)
        fmin = f.flatten(1).amin(1).view(-1, 1, 1, 1)
        fmax = f.flatten(1).amax(1).view(-1, 1, 1, 1)
        return 2 * (f - fmin) / (fmax - fmin).clamp_min(1e-6) - 1

    def sample_tau(self, B, H, W, device, generator=None, force_field: Optional[bool] = None) -> torch.Tensor:
        """Clock fields for training. Fixes the old 1/sigma 'importance' sampling that almost
        exclusively drew near-clean timesteps."""
        cfg = self.cfg
        u = _rand((B,), device, generator)
        if cfg.tau_sampling == "uniform":
            c = u
        else:
            ln = torch.sigmoid(cfg.logit_mean + cfg.logit_std * _randn((B,), device, generator))
            c = ln if cfg.tau_sampling == "logit_normal" else torch.where(_rand((B,), device, generator) < 0.5, u, ln)
        c = c.clamp(0, 1)
        tau = c.view(B, 1, 1, 1).expand(B, 1, H, W).clone()
        if force_field is None:
            sel = _rand((B,), device, generator) < cfg.field_prob
        else:
            sel = torch.full((B,), bool(force_field), device=device)
        if bool(sel.any()):
            n = int(sel.sum())
            f = self._random_field(n, H, W, device, generator)
            amp = cfg.field_spread * (0.2 + 0.8 * _rand((n,), device, generator))
            tau[sel] = (c[sel].view(-1, 1, 1, 1) + amp.view(-1, 1, 1, 1) * f).clamp(0, 1)
        return tau

    # ---- network call ----------------------------------------------------------------------
    def sigma_bar(self, tau: torch.Tensor, kind: torch.Tensor) -> torch.Tensor:
        return self.degradation.sigma(tau.float()).flatten(1).mean(1) * (kind == BLUR).float()

    def denoise(self, x_t, tau, kind, self_cond=None) -> Dict[str, torch.Tensor]:
        B, C, H, W = x_t.shape
        if tau.dim() == 1:
            tau = tau.view(B, 1, 1, 1).expand(B, 1, H, W)
        m = self.pad_multiple
        ph, pw = (m - H % m) % m, (m - W % m) % m

        def pad(t, mode="reflect"):
            return F.pad(t, (0, pw, 0, ph), mode=mode) if (ph or pw) else t

        sc = pad(self_cond) if (self_cond is not None and self.cfg.self_condition) else None
        out = self.model(pad(x_t), pad(tau.float(), "replicate"), self.sigma_bar(tau, kind), kind, sc)
        return {k: (v[..., :H, :W] if isinstance(v, torch.Tensor) and v.dim() == 4 else v) for k, v in out.items()}

    def forward(self, x_t, tau, kind, self_cond=None):
        return self.denoise(x_t, tau, kind, self_cond)

    def estimate_clock(self, y: torch.Tensor, smooth_sigma: Optional[float] = None) -> Dict[str, torch.Tensor]:
        est = self.clock_estimator(y)
        s = self.cfg.clock_smooth_sigma if smooth_sigma is None else smooth_sigma
        scale = est["tau_logscale"].float().exp()
        if s > 0:
            est["tau_smooth"] = SpectralClockEstimator.smooth(est["tau_mu"], est["tau_logscale"], s)
            est["scale_smooth"] = SpectralClockEstimator.smooth(scale, est["tau_logscale"], s)
        else:
            est["tau_smooth"], est["scale_smooth"] = est["tau_mu"], scale
        # Risk-averse clock: over-estimating the blur causes ringing / hallucination, under-estimating
        # only leaves residual blur -> use a lower confidence bound of the Laplace posterior.
        est["tau_lcb"] = (est["tau_smooth"] - self.cfg.blind_clock_margin * est["scale_smooth"]).clamp(0, 1)
        return est

    # ---- sampler building blocks -------------------------------------------------------------
    def cold_step(self, x_t, x0_hat, t_map, s_map, kind, state) -> torch.Tensor:
        """
        Bansal et al. Algorithm 2 generalised to clock fields:
            x_s = x_t - D(x0_hat, t) + D(x0_hat, s).
        For noise-type samples the noise realisation is re-estimated from the current state
        (eps_hat = (x_t - x0_hat)/n_t, i.e. DDIM) - it is *never* taken from ground truth,
        which would leak x0.
        """
        st = dict(state)
        is_noise = (kind == NOISE).view(-1, 1, 1, 1)
        if bool(is_noise.any()):
            n_t = self.degradation.noise_level(t_map)
            eps_hat = (x_t - x0_hat) / n_t.clamp_min(1e-4)
            eps_hat = torch.where(n_t > 1e-4, eps_hat, st["noise"])
            st["noise"] = torch.where(is_noise, eps_hat, st["noise"])
        d_t, _ = self.degradation.apply(x0_hat, t_map, kind, st)
        d_s, _ = self.degradation.apply(x0_hat, s_map, kind, st)
        return x_t - d_t + d_s

    def range_null(self, x0_hat, y, tau_obs, kind, state, eta: float, lam: float) -> torch.Tensor:
        """Spectral range-null anchoring of x0_hat to the observation y.   [N2]"""
        if eta <= 0:
            return x0_hat
        deg = self.degradation
        out = x0_hat.clone()
        for k_idx, name in enumerate(KINDS):
            sel = kind == k_idx
            if name == "noise" or not bool(sel.any()):
                continue
            idx = sel.nonzero(as_tuple=True)[0]
            xs, ys, ts = x0_hat[idx], y[idx], tau_obs[idx]
            st = {k: v[idx] for k, v in state.items()}
            ks = kind[idx]
            if name == "mask":  # exact projection: observed pixels are the range space
                corr = (st["rank"] >= deg.mask_ratio(ts)).float() * (ys - xs)
            elif name == "downsample":  # iterative back-projection
                corr = ys - deg.apply(xs, ts, ks, st)[0]
            else:  # blur: Wiener range-space pseudo-inverse of the heat operator
                corr = deg.wiener_backproject(ys - deg.apply(xs, ts, ks, st)[0], ts, lam)
            out[idx] = xs + eta * corr
        return out

    # ---- restoration ---------------------------------------------------------------------------
    @torch.no_grad()
    def restore(self, y: torch.Tensor, tau_obs: Optional[torch.Tensor] = None, kind: Optional[torch.Tensor] = None,
                steps: Optional[int] = None, sampler: Optional[str] = None, strength: float = 1.0,
                churn: Optional[float] = None, eta: Optional[float] = None, lam: Optional[float] = None,
                record: bool = False, observed: Optional[torch.Tensor] = None, generator=None,
                x0_gt: Optional[torch.Tensor] = None) -> Dict[str, Any]:
        """
        Restore observations y (B, C, H, W) in [-1, 1].
        tau_obs=None -> blind: the clock field is estimated (Spectral Clock Estimator) and
        multiplied by `strength` (user control of the restoration strength).
        Synchronised Field Descent: tau_k(x) = tau_obs(x) * (1 - k/K)^rho for all pixels.
        """
        cfg = self.cfg
        sampler = sampler or cfg.sampler
        churn = cfg.churn if churn is None else churn
        eta = cfg.rn_eta if eta is None else eta
        blind = tau_obs is None
        if lam is None:  # an *estimated* operator is uncertain -> stronger Wiener regularisation
            lam = cfg.rn_lambda_real if blind else cfg.rn_lambda
        y = y.float()
        B, C, H, W = y.shape
        info: Dict[str, Any] = {}
        est = None
        if tau_obs is None or kind is None:
            est = self.estimate_clock(y)
            info["clock"] = {k: v for k, v in est.items() if k != "physics"}
        if kind is None:
            if cfg.degradation_type == "mixed":
                kind = est["type_logits"].argmax(1)
            else:
                kind = torch.full((B,), KINDS.index(cfg.degradation_type), dtype=torch.long, device=y.device)
        if tau_obs is None:
            tau_obs = (est["tau_lcb"] * strength).clamp(0, 1)
        elif tau_obs.dim() == 1:
            tau_obs = tau_obs.view(B, 1, 1, 1).expand(B, 1, H, W)
        tau_obs = tau_obs.float()
        state = self.degradation.new_state(y, generator)
        state["rank"] = self.degradation.infer_rank(y, tau_obs, observed, generator)

        K = int(steps or cfg.sample_steps)
        if sampler == "direct":
            K = 1
        elif cfg.adaptive_steps:
            K = max(min(cfg.min_steps, K), int(math.ceil(K * float(tau_obs.max().clamp(min=1e-3)))))
        u = [(1 - k / K) ** cfg.step_rho for k in range(K + 1)]

        x = y.clone()
        x0_prev, x0, log_scale = None, y.clone(), None
        traj, traj_x0, traj_tau, traj_psnr, traj_unc = [], [], [], [], []
        for k in range(K):
            t_map, s_map = tau_obs * u[k], tau_obs * u[k + 1]
            out = self.denoise(x, t_map, kind, self_cond=x0_prev)
            x0 = out["x0"].float().clamp(-1, 1)
            log_scale = out["log_scale"]
            if sampler == "srn":
                x0 = self.range_null(x0, y, tau_obs, kind, state, eta, lam).clamp(-1, 1)
            if churn > 0 and log_scale is not None and k < K - 1:  # uncertainty-gated stochasticity [N6]
                b = log_scale.float().exp()
                uu = _rand(x0.shape, x0.device, generator) - 0.5
                x0 = (x0 - churn * u[k + 1] * b * torch.sign(uu) * torch.log1p(-2 * uu.abs().clamp(max=0.4999))).clamp(-1, 1)
            if sampler == "direct":
                x = x0
            elif sampler == "naive":  # Algorithm 1
                x = self.degradation.apply(x0, s_map, kind, state)[0]
            else:  # Algorithm 2 (+ range-null for srn)
                x = self.cold_step(x, x0, t_map, s_map, kind, state)
            x0_prev = x0
            if record:
                traj.append(x.detach().cpu())
                traj_x0.append(x0.detach().cpu())
                traj_tau.append(float(t_map.mean()))
                if log_scale is not None:
                    traj_unc.append(log_scale.float().exp().mean().item())
                if x0_gt is not None:
                    traj_psnr.append(psnr(x0, x0_gt).mean().item())
        info.update({
            "output": x.clamp(-1, 1), "x0": x0, "tau_obs": tau_obs, "kind": kind, "steps": K, "sampler": sampler,
            "uncertainty": log_scale.float().exp() if log_scale is not None else None,
            "trajectory": traj, "x0_trajectory": traj_x0, "tau_trajectory": traj_tau,
            "psnr_trajectory": traj_psnr, "uncertainty_trajectory": traj_unc,
        })
        return info

    # ---- generation from a degraded prior  [N8] -------------------------------------------------
    def generation_kind(self) -> Optional[str]:
        dt = self.cfg.degradation_type
        if dt in ("blur", "mixed"):
            return "blur"
        if dt in ("downsample", "noise"):
            return dt
        return None  # a fully masked image carries no information to sample from

    @torch.no_grad()
    def fit_prior(self, loader, device=None, max_images: Optional[int] = None) -> bool:
        name = self.generation_kind()
        if name is None:
            print("[prior] generation is not defined for the 'mask' degradation - skipped.")
            return False
        device = device or self.prior_mean.device
        max_images = max_images or self.cfg.prior_max_images
        feats, n = [], 0
        for batch in loader:
            x = batch["image"].to(device).float()
            if name in ("blur", "downsample"):
                kind = torch.full((x.shape[0],), KINDS.index(name), dtype=torch.long, device=device)
                x, _ = self.degradation.apply(x, torch.ones(x.shape[0], device=device), kind)
            feats.append(F.adaptive_avg_pool2d(x, self.cfg.prior_res).flatten(1).double().cpu())
            n += x.shape[0]
            if n >= max_images:
                break
        if not feats:
            return False
        X = torch.cat(feats, 0)
        N, D = X.shape
        mu = X.mean(0)
        Xc = X - mu
        cov = Xc.T @ Xc / max(N - 1, 1)
        alpha = D / (N + D)  # shrinkage towards a scaled identity
        cov = (1 - alpha) * cov + alpha * (cov.trace() / D) * torch.eye(D, dtype=cov.dtype) + 1e-6 * torch.eye(D, dtype=cov.dtype)
        L = torch.linalg.cholesky(cov)
        self.prior_mean.copy_(mu.float().to(self.prior_mean.device))
        self.prior_factor.copy_(L.float().to(self.prior_factor.device))
        self.prior_ready.fill_(1.0)
        print(f"[prior] fitted a {D}-dim Gaussian degraded prior on {N} images ({name}).")
        return True

    @torch.no_grad()
    def generate(self, n: int, image_size: Tuple[int, int], steps: Optional[int] = None,
                 churn: Optional[float] = None, generator=None, record: bool = False) -> Dict[str, Any]:
        if float(self.prior_ready.item()) < 0.5:
            raise RuntimeError("Degraded prior not fitted - call fit_prior() first.")
        name = self.generation_kind()
        C, p = self.cfg.in_channels, self.cfg.prior_res
        dev = self.prior_mean.device
        z = self.prior_mean[None] + _randn((n, self.prior_mean.numel()), dev, generator) @ self.prior_factor.T
        x = F.interpolate(z.view(n, C, p, p), size=tuple(image_size), mode="bicubic", align_corners=False).clamp(-1, 1)
        kind = torch.full((n,), KINDS.index(name), dtype=torch.long, device=dev)
        tau = torch.ones(n, 1, *image_size, device=dev)
        x_T, _ = self.degradation.apply(x, tau, kind, generator=generator)
        res = self.restore(x_T, tau_obs=tau, kind=kind, steps=steps or self.cfg.generate_steps, sampler="srn",
                           churn=self.cfg.gen_churn if churn is None else churn, record=record, generator=generator)
        res["prior_sample"] = x_T
        return res


