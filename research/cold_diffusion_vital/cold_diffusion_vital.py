def radial_power_spectrum(x: torch.Tensor, n_bins: int = 64) -> Tuple[np.ndarray, np.ndarray]:
    """Radially averaged log power spectrum of the luminance of (C, H, W) or (1, C, H, W)."""
    if x.dim() == 4:
        x = x[0]
    lum = to01(x.float()).mean(0)
    lum = lum - lum.mean()
    H, W = lum.shape
    win = torch.hann_window(H, device=lum.device)[:, None] * torch.hann_window(W, device=lum.device)[None, :]
    P = torch.fft.fftshift(torch.fft.fft2(lum * win)).abs() ** 2
    yy, xx = torch.meshgrid(torch.arange(H, device=lum.device) - H // 2, torch.arange(W, device=lum.device) - W // 2, indexing="ij")
    r = torch.sqrt((yy.float() / (H / 2)) ** 2 + (xx.float() / (W / 2)) ** 2)  # 1 == Nyquist
    idx = torch.clamp((r / math.sqrt(2) * n_bins).long(), max=n_bins - 1).flatten()
    num = torch.zeros(n_bins, device=lum.device).index_add_(0, idx, P.flatten())
    den = torch.zeros(n_bins, device=lum.device).index_add_(0, idx, torch.ones_like(P.flatten()))
    prof = torch.log10(num / den.clamp_min(1) + 1e-12)
    freqs = (torch.arange(n_bins, device=lum.device).float() + 0.5) / n_bins * math.sqrt(2)
    return freqs.cpu().numpy(), prof.cpu().numpy()


def null_space_recovery(pred, target, degraded, tau, kind, deg: ColdDegradation, thresh: float = 0.5) -> torch.Tensor:
    """
    NSR: the fraction of the *annihilated* spectral error that restoration removed:
        1 - sum_w M |F(x0_hat - x0)| / sum_w M |F(y - x0)|,   M = [1 - |K_tau|^2 > thresh]
    (1 = perfect recovery of the destroyed frequencies, 0 = no better than the input).
    """
    with autocast_off(pred.device.type):
        h, w = pred.shape[-2:]
        Wt = deg.annihilation_weight(tau, kind, h, w, 1.0, 0.0)
        M = (Wt > thresh).float()
        e_pred = (HeatKernel.spectrum(pred.float() - target.float()).abs() * M).flatten(1).sum(1)
        e_in = (HeatKernel.spectrum(degraded.float() - target.float()).abs() * M).flatten(1).sum(1)
        return 1 - e_pred / e_in.clamp_min(1e-8)


def pearson(a: torch.Tensor, b: torch.Tensor) -> float:
    a, b = a.flatten().float(), b.flatten().float()
    a, b = a - a.mean(), b - b.mean()
    return float((a * b).sum() / (a.norm() * b.norm() + 1e-12))


