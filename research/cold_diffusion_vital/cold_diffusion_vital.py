def to_2tuple(x):
    """Convert input to a tuple of length 2."""
    if isinstance(x, (tuple, list)) and len(x) == 2:
        return tuple(x)
    return (x, x)


def ndgrid(*tensors):
    """Create n-dimensional grid."""
    return torch.meshgrid(*tensors, indexing="ij")


def num_groups(channels: int, max_groups: int = 8) -> int:
    g = min(max_groups, channels)
    while channels % g:
        g -= 1
    return g


def to01(x: torch.Tensor) -> torch.Tensor:
    """[-1, 1] -> [0, 1]."""
    return (x.clamp(-1, 1) + 1) / 2


def count_parameters(module: nn.Module) -> int:
    return sum(p.numel() for p in module.parameters())


def autocast_off(device_type: str):
    """FFTs are run in fp32 (half-precision FFT is inaccurate and size-restricted)."""
    return torch.autocast(device_type=device_type, enabled=False)


def _rand(shape, device, generator=None):
    if generator is None:
        return torch.rand(*shape, device=device)
    return torch.rand(*shape, generator=generator).to(device)


def _randn(shape, device, generator=None):
    if generator is None:
        return torch.randn(*shape, device=device)
    return torch.randn(*shape, generator=generator).to(device)


def colorize(t: Union[torch.Tensor, np.ndarray], cmap: str = "magma",
             vmin: Optional[float] = None, vmax: Optional[float] = None) -> torch.Tensor:
    """(H, W) map -> (3, H, W) RGB tensor in [0, 1] using a matplotlib colormap."""
    a = t.detach().float().cpu().numpy() if isinstance(t, torch.Tensor) else np.asarray(t, dtype=np.float32)
    a = np.squeeze(a)
    lo = float(np.nanmin(a)) if vmin is None else vmin
    hi = float(np.nanmax(a)) if vmax is None else vmax
    a = np.clip((a - lo) / max(hi - lo, 1e-8), 0, 1)
    try:  # matplotlib >= 3.5 (cm.get_cmap was removed in 3.9)
        cmap_fn = matplotlib.colormaps[cmap]
    except AttributeError:
        cmap_fn = cm.get_cmap(cmap)
    rgb = cmap_fn(a)[..., :3]
    return torch.from_numpy(rgb).permute(2, 0, 1).float()


def tensor_to_pil(x: torch.Tensor) -> Image.Image:
    """(3, H, W) or (1, 3, H, W) in [-1, 1] -> PIL."""
    if x.dim() == 4:
        x = x[0]
    arr = (to01(x).permute(1, 2, 0).cpu().numpy() * 255).round().astype(np.uint8)
    return Image.fromarray(arr)


def save_gif(frames: Sequence[torch.Tensor], path: Union[str, Path], duration: int = 80):
    """frames: (3, H, W) tensors in [0, 1]."""
    imgs = [Image.fromarray((f.clamp(0, 1).permute(1, 2, 0).cpu().numpy() * 255).astype(np.uint8)) for f in frames]
    if imgs:
        imgs[0].save(path, save_all=True, append_images=imgs[1:], duration=duration, loop=0)


def save_json(obj: Any, path: Union[str, Path]):
    def _default(o):
        if isinstance(o, (np.floating, np.integer)):
            return o.item()
        if isinstance(o, torch.Tensor):
            return o.detach().cpu().tolist()
        if isinstance(o, Path):
            return str(o)
        return str(o)

    with open(path, "w") as f:
        json.dump(obj, f, indent=2, default=_default)


