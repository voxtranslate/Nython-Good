class HeatKernel:
    """
    Exact isotropic heat-kernel (Gaussian) blur with reflective (Neumann) boundaries.   [N7]

    The image is even-symmetrically extended to 2H x 2W and filtered in the Fourier domain
    with the analytic transfer function K_sigma(w) = exp(-sigma^2 |w|^2 / 2). This is exactly
    the DCT-II diagonalisation of the heat equation used in inverse heat dissipation, so it is
    valid for *any* continuous sigma (no kernel truncation, no dark zero-padded borders)
    and it is cheap even for sigma = 30 px.
    """

    _cache: Dict[Tuple[int, int, str], torch.Tensor] = {}

    @staticmethod
    def omega_sq(h: int, w: int, device) -> torch.Tensor:
        key = (h, w, str(device))
        if key not in HeatKernel._cache:
            wy = torch.fft.fftfreq(2 * h, device=device) * (2 * math.pi)
            wx = torch.fft.rfftfreq(2 * w, device=device) * (2 * math.pi)
            HeatKernel._cache[key] = (wy[:, None] ** 2 + wx[None, :] ** 2).float()
        return HeatKernel._cache[key]

    @staticmethod
    def spectrum(x: torch.Tensor) -> torch.Tensor:
        x = x.float()
        x = torch.cat([x, x.flip(-1)], dim=-1)
        x = torch.cat([x, x.flip(-2)], dim=-2)
        return torch.fft.rfft2(x)

    @staticmethod
    def inverse(X: torch.Tensor, h: int, w: int) -> torch.Tensor:
        return torch.fft.irfft2(X, s=(2 * h, 2 * w))[..., :h, :w]

    @staticmethod
    def transfer(sigma, h: int, w: int, device) -> torch.Tensor:
        """sigma: scalar or (B,) -> (B, 1, 2h, w+1) real transfer function."""
        sigma = torch.as_tensor(sigma, device=device, dtype=torch.float32).reshape(-1, 1, 1, 1)
        return torch.exp(-0.5 * sigma ** 2 * HeatKernel.omega_sq(h, w, device))

    @staticmethod
    def blur(x: torch.Tensor, sigma) -> torch.Tensor:
        with autocast_off(x.device.type):
            h, w = x.shape[-2:]
            out = HeatKernel.inverse(HeatKernel.spectrum(x) * HeatKernel.transfer(sigma, h, w, x.device), h, w)
        return out


class ColdDegradation(nn.Module):
    """
    Deterministic degradation operators D(x, tau) with a *continuous* clock tau in [0, 1],
    either a scalar per image or a per-pixel clock field tau(x) (B, 1, H, W).          [N1]

        blur        exact Neumann heat dissipation, sigma(tau) from the schedule
        noise       x + n(tau) * eps     (eps is part of the per-sample state)
        mask        x * [rank(x) >= tau] (a fixed rank field -> nested masks, as Algorithm 2 needs)
        downsample  area-down / bilinear-up with scale s(tau)

    Spatially varying fields use exact per-pixel formulas (noise, mask) or a bank of anchor
    levels interpolated per pixel (blur, downsample).
    """

    def __init__(self, cfg: Config):
        super().__init__()
        self.schedule_type = cfg.schedule_type
        self.min_sigma = cfg.min_sigma
        self.max_sigma = cfg.max_sigma
        self.noise_max = cfg.noise_max
        self.min_scale = cfg.min_downsample_scale
        self.n_anchors = max(2, cfg.field_anchors)
        self.register_buffer("anchors", torch.linspace(0, 1, self.n_anchors), persistent=False)

    # ---- schedules (all exactly the identity at tau = 0) --------------------------------
    def sigma(self, tau: torch.Tensor) -> torch.Tensor:
        tau = tau.clamp(0, 1)
        if self.schedule_type == "linear":
            return self.max_sigma * tau
        if self.schedule_type == "sqrt":  # heat time (sigma^2) linear in tau
            return self.max_sigma * tau.sqrt()
        if self.schedule_type == "cosine":
            return self.max_sigma * (1 - torch.cos(0.5 * math.pi * tau))
        if self.schedule_type == "log":  # perceptually uniform, sigma(0) = 0, sigma(1) = max
            r = 1.0 + self.max_sigma / self.min_sigma
            return self.min_sigma * (torch.pow(torch.as_tensor(r, device=tau.device), tau) - 1.0)
        raise ValueError(f"Unknown schedule type: {self.schedule_type}")

    def noise_level(self, tau):
        return self.noise_max * tau.clamp(0, 1)

    def mask_ratio(self, tau):
        return tau.clamp(0, 1)

    def scale(self, tau):
        return 1.0 - tau.clamp(0, 1) * (1.0 - self.min_scale)

    # ---- per-sample deterministic randomness -------------------------------------------
    def new_state(self, x: torch.Tensor, generator=None) -> Dict[str, torch.Tensor]:
        B, C, H, W = x.shape
        return {"noise": _randn((B, C, H, W), x.device, generator), "rank": self.rank_field(B, H, W, x.device, generator)}

    @staticmethod
    def rank_field(B, H, W, device, generator=None) -> torch.Tensor:
        """Blobby random order with an exactly uniform marginal: mask ratio == tau."""
        r = int(_rand((1,), "cpu", generator).item() * 12) + 4
        low = _rand((B, 1, r, r), device, generator)
        f = F.interpolate(low, size=(H, W), mode="bicubic", align_corners=False)
        f = f + 0.25 * _rand((B, 1, H, W), device, generator)
        order = f.flatten(1).argsort(1).argsort(1).float() / max(H * W - 1, 1)
        return order.view(B, 1, H, W)

    def infer_rank(self, y, tau_obs, observed=None, generator=None) -> torch.Tensor:
        """Rank field consistent with an observed masked image (the true order is unknown)."""
        if observed is None:
            observed = y.abs().sum(1, keepdim=True) > 1e-6
        m = self.mask_ratio(tau_obs)
        u = _rand(tau_obs.shape, y.device, generator)
        return torch.where(observed, m + (1 - m) * u, m * u)

    @staticmethod
    def is_uniform(tau: torch.Tensor) -> torch.Tensor:
        flat = tau.flatten(1)
        return (flat.amax(1) - flat.amin(1)) < 1e-6

    # ---- operators -----------------------------------------------------------------------
    def _downsample(self, x, s: float):
        H, W = x.shape[-2:]
        h2, w2 = max(1, int(round(H * s))), max(1, int(round(W * s)))
        if h2 == H and w2 == W:
            return x
        return F.interpolate(F.interpolate(x, size=(h2, w2), mode="area"), size=(H, W), mode="bilinear", align_corners=False)

    def _uniform(self, x, t: torch.Tensor, name: str, state) -> torch.Tensor:
        """Exact operator, one scalar t per sample (t: (B,))."""
        if name == "blur":
            return HeatKernel.blur(x, self.sigma(t))
        if name == "noise":
            return x + self.noise_level(t).view(-1, 1, 1, 1) * state["noise"]
        if name == "mask":
            return x * (state["rank"] >= self.mask_ratio(t).view(-1, 1, 1, 1)).to(x.dtype)
        if name == "downsample":
            s = self.scale(t)
            return torch.cat([self._downsample(x[i:i + 1], float(s[i])) for i in range(x.shape[0])], 0)
        raise ValueError(name)

    def _anchor_weights(self, tau):
        pos = tau.clamp(0, 1) * (self.n_anchors - 1)
        lo = pos.floor().clamp(max=self.n_anchors - 2)
        frac = pos - lo
        used = torch.unique(torch.cat([lo.flatten(), lo.flatten() + 1])).long().tolist()
        for a in used:
            w = (lo == a).to(tau.dtype) * (1 - frac) + (lo + 1 == a).to(tau.dtype) * frac
            yield a, w

    def _field(self, x, tau, name: str, state) -> torch.Tensor:
        """Spatially varying operator (tau: (B, 1, H, W))."""
        if name == "noise":
            return x + self.noise_level(tau) * state["noise"]
        if name == "mask":
            return x * (state["rank"] >= self.mask_ratio(tau)).to(x.dtype)
        B = x.shape[0]
        out = torch.zeros_like(x)
        if name == "blur":
            with autocast_off(x.device.type):
                h, w = x.shape[-2:]
                X = HeatKernel.spectrum(x)
                for a, wa in self._anchor_weights(tau):
                    sig = self.sigma(self.anchors[a:a + 1])
                    out = out + wa * HeatKernel.inverse(X * HeatKernel.transfer(sig, h, w, x.device), h, w)
            return out
        for a, wa in self._anchor_weights(tau):  # downsample
            t = self.anchors[a].expand(B)
            out = out + wa * self._uniform(x, t, name, state)
        return out

    def apply(self, x: torch.Tensor, tau: torch.Tensor, kind: torch.Tensor,
              state: Optional[Dict[str, torch.Tensor]] = None, generator=None):
        """
        x: (B, C, H, W) clean-ish image; tau: (B,) or (B, 1, H, W); kind: (B,) long.
        Returns (D(x, tau), state). Differentiable w.r.t. x.
        """
        x = x.float()
        B, C, H, W = x.shape
        if tau.dim() == 1:
            tau = tau.view(B, 1, 1, 1).expand(B, 1, H, W)
        tau = tau.float()
        if state is None:
            state = self.new_state(x, generator)
        uni = self.is_uniform(tau)
        out = torch.zeros_like(x)
        for k_idx, name in enumerate(KINDS):
            sel_k = kind == k_idx
            if not bool(sel_k.any()):
                continue
            for uniform in (True, False):
                sel = sel_k & (uni if uniform else ~uni)
                if not bool(sel.any()):
                    continue
                idx = sel.nonzero(as_tuple=True)[0]
                st = {k: v[idx] for k, v in state.items()}
                if uniform:
                    ys = self._uniform(x[idx], tau[idx, 0, 0, 0], name, st)
                else:
                    ys = self._field(x[idx], tau[idx], name, st)
                out = out.index_copy(0, idx, ys.float())
        return out, state

    def wiener_backproject(self, resid: torch.Tensor, tau: torch.Tensor, lam: float) -> torch.Tensor:
        """
        Range-space pseudo-inverse of the heat operator applied to a residual:   [N2]
            F^-1[ K/(K^2 + lam) * F(resid) ]
        (local anchors for clock fields). Frequencies with K^2 >> lam are recovered from the
        data, frequencies in the numerical null space (K^2 << lam) are left to the network.
        """
        with autocast_off(resid.device.type):
            B, C, h, w = resid.shape
            R = HeatKernel.spectrum(resid)
            out = torch.zeros_like(resid, dtype=torch.float32)
            uni = self.is_uniform(tau)
            if bool(uni.any()):
                idx = uni.nonzero(as_tuple=True)[0]
                K = HeatKernel.transfer(self.sigma(tau[idx, 0, 0, 0]), h, w, resid.device)
                out = out.index_copy(0, idx, HeatKernel.inverse(R[idx] * K / (K ** 2 + lam), h, w))
            if bool((~uni).any()):
                idx = (~uni).nonzero(as_tuple=True)[0]
                acc = torch.zeros_like(resid[idx], dtype=torch.float32)
                for a, wa in self._anchor_weights(tau[idx]):
                    K = HeatKernel.transfer(self.sigma(self.anchors[a:a + 1]), h, w, resid.device)
                    acc = acc + wa * HeatKernel.inverse(R[idx] * K / (K ** 2 + lam), h, w)
                out = out.index_copy(0, idx, acc)
        return out

    def annihilation_weight(self, tau: torch.Tensor, kind: torch.Tensor, h: int, w: int,
                            gamma: float, floor: float) -> torch.Tensor:
        """
        W(w) = (1 - |K_tau(w)|^2)^gamma + floor on the (2h, w+1) spectrum grid:   [N5]
        how much of each frequency the degradation destroyed.
        """
        w2 = HeatKernel.omega_sq(h, w, tau.device)
        B = tau.shape[0]
        flat = tau.reshape(B, -1).float()
        sig_eff = self.sigma(flat).pow(2).mean(1).sqrt()  # RMS blur of the field
        K2 = torch.exp(-(sig_eff.view(-1, 1, 1, 1) ** 2) * w2)
        s = self.scale(flat.mean(1)).view(-1, 1, 1, 1)
        K2_ds = torch.sigmoid((s * math.pi - w2.sqrt()) / (0.05 * math.pi)) ** 2
        K2 = torch.where((kind == DOWNSAMPLE).view(-1, 1, 1, 1), K2_ds, K2)
        Wt = (1 - K2).clamp_min(0) ** gamma + floor
        flatW = torch.ones_like(Wt)
        use = ((kind == BLUR) | (kind == DOWNSAMPLE)).view(-1, 1, 1, 1)
        return torch.where(use, Wt, flatW)


