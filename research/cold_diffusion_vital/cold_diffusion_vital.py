def psnr(pred: torch.Tensor, target: torch.Tensor) -> torch.Tensor:
    """Per-image PSNR (dB) of [-1, 1] images, computed on [0, 1]."""
    mse = ((to01(pred.float()) - to01(target.float())) ** 2).flatten(1).mean(1).clamp_min(1e-10)
    return 10 * torch.log10(1.0 / mse)


def _gaussian_window(size: int = 11, sigma: float = 1.5, channels: int = 3, device="cpu"):
    g = torch.exp(-((torch.arange(size, device=device).float() - size // 2) ** 2) / (2 * sigma ** 2))
    g = g / g.sum()
    return (g[:, None] @ g[None, :]).expand(channels, 1, size, size).contiguous()


def ssim(pred: torch.Tensor, target: torch.Tensor) -> torch.Tensor:
    """Per-image SSIM (Wang et al. 2004), Gaussian window 11/1.5, on [0, 1]."""
    x, y = to01(pred.float()), to01(target.float())
    C = x.shape[1]
    size = min(11, min(x.shape[-2:]))
    size = size if size % 2 else size - 1
    win = _gaussian_window(max(size, 1), 1.5, C, x.device)
    c1, c2 = 0.01 ** 2, 0.03 ** 2
    mu_x, mu_y = F.conv2d(x, win, groups=C), F.conv2d(y, win, groups=C)
    sxx = F.conv2d(x * x, win, groups=C) - mu_x ** 2
    syy = F.conv2d(y * y, win, groups=C) - mu_y ** 2
    sxy = F.conv2d(x * y, win, groups=C) - mu_x * mu_y
    s = ((2 * mu_x * mu_y + c1) * (2 * sxy + c2)) / ((mu_x ** 2 + mu_y ** 2 + c1) * (sxx + syy + c2))
    return s.flatten(1).mean(1)


class LPIPSMetric:
    """LPIPS through pyiqa (optional)."""

