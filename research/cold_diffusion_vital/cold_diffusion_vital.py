class PerceptualLoss(nn.Module):
    """Optional VGG16 feature loss (needs the torchvision weights; disabled by default)."""

    def __init__(self, layers: Sequence[int] = (3, 8, 15, 22)):
        super().__init__()
        from torchvision.models import VGG16_Weights, vgg16

        vgg = vgg16(weights=VGG16_Weights.IMAGENET1K_V1).features[: max(layers) + 1].eval()
        for p in vgg.parameters():
            p.requires_grad_(False)
        self.vgg = vgg
        self.layers = set(layers)
        self.register_buffer("mean", torch.tensor([0.485, 0.456, 0.406]).view(1, 3, 1, 1))
        self.register_buffer("std", torch.tensor([0.229, 0.224, 0.225]).view(1, 3, 1, 1))

    def forward(self, pred, target):
        x = (to01(pred) - self.mean) / self.std
        y = (to01(target) - self.mean) / self.std
        loss = 0.0
        for i, layer in enumerate(self.vgg):
            x, y = layer(x), layer(y)
            if i in self.layers:
                loss = loss + F.l1_loss(x, y)
        return loss


class ColdDiffusionLoss(nn.Module):
    """
    Full training objective of ViTAL-CF:

        L = l_rec  * Charbonnier(x0_hat, x0)
          + l_unc  * beta-Laplace NLL (scale head only, mean-decoupled)          [N6]
          + l_freq * Null-Space Spectral loss  sum_w W_tau(w) |F(x0_hat - x0)|    [N5]
          + l_cyc  * || D(x0_hat, tau) - x_tau ||_1   (re-degradation consistency)
          + l_roll * Charbonnier(R(x_s^alg2, s, sc=x0_hat), x0)                  [N4]
          + l_clk  * clock-estimator Laplace NLL + L1 + TV                       [N1]
          + l_type * CE(type)            (mixed mode)
          + l_perc * VGG perceptual      (optional)
    """

    def __init__(self, cfg: Config):
        super().__init__()
        self.cfg = cfg
        self.perceptual = None
        if cfg.lambda_perceptual > 0:
            try:
                self.perceptual = PerceptualLoss()
            except Exception as e:  # noqa: BLE001 (no internet on Kaggle, ...)
                print(f"[loss] perceptual loss disabled: {e}")

    @staticmethod
    def charbonnier(pred, target, eps: float = 1e-3):
        return torch.sqrt((pred.float() - target.float()) ** 2 + eps ** 2).mean()

    @staticmethod
    def beta_laplace_nll(mean, target, log_scale, beta: float = 1.0):
        """
        Laplace NLL |e|/b + log b with the error detached (the mean is trained by the
        reconstruction loss only) and beta-weighting stopgrad(b)^beta (Seitzer et al. 2022),
        which gives the well-conditioned gradient b - |e| for beta = 1.
        """
        log_scale = log_scale.float()
        b = log_scale.exp()
        err = (target.float() - mean.float()).abs().detach()
        w = b.detach() ** beta if beta > 0 else 1.0
        return (w * (err / b + log_scale)).mean()

    def null_space_spectral(self, pred, target, tau, kind, deg: ColdDegradation):
        with autocast_off(pred.device.type):
            diff = pred.float() - target.float()
            h, w = diff.shape[-2:]
            D = HeatKernel.spectrum(diff).abs() / (2.0 * math.sqrt(h * w))
            Wt = deg.annihilation_weight(tau, kind, h, w, self.cfg.nss_gamma, self.cfg.nss_floor)
            per = (Wt * D).flatten(1).sum(1) / (Wt.expand_as(D).flatten(1).sum(1) + 1e-8)
            return per.mean()

    @staticmethod
    def total_variation(x):
        return (x[..., 1:, :] - x[..., :-1, :]).abs().mean() + (x[..., :, 1:] - x[..., :, :-1]).abs().mean()

    def forward(self, diffusion: ColdDiffusionModel, x0: torch.Tensor, tau: Optional[torch.Tensor] = None,
                kind: Optional[torch.Tensor] = None, generator=None, rollout: Optional[bool] = None):
        cfg = self.cfg
        x0 = x0.float()
        B, C, H, W = x0.shape
        dev = x0.device
        if kind is None:
            kind = diffusion.sample_kind(B, dev, generator)
        if tau is None:
            tau = diffusion.sample_tau(B, H, W, dev, generator)
        elif tau.dim() == 1:
            tau = tau.view(B, 1, 1, 1).expand(B, 1, H, W).contiguous()
        deg = diffusion.degradation
        x_t, state = deg.apply(x0, tau, kind, generator=generator)

        out = diffusion.denoise(x_t, tau, kind)
        x0_hat = out["x0"].float()
        logs: Dict[str, float] = {}
        total = cfg.lambda_rec * self.charbonnier(x0_hat, x0)
        logs["rec"] = F.l1_loss(x0_hat, x0).item()

        if out["log_scale"] is not None and cfg.lambda_unc > 0:
            l_unc = self.beta_laplace_nll(x0_hat, x0, out["log_scale"])
            total = total + cfg.lambda_unc * l_unc
            logs["unc"] = l_unc.item()
        if cfg.lambda_freq > 0:
            l_freq = self.null_space_spectral(x0_hat, x0, tau, kind, deg)
            total = total + cfg.lambda_freq * l_freq
            logs["freq"] = l_freq.item()
        if cfg.lambda_cycle > 0:
            d_hat, _ = deg.apply(x0_hat, tau, kind, state)
            l_cyc = F.l1_loss(d_hat, x_t)
            total = total + cfg.lambda_cycle * l_cyc
            logs["cycle"] = l_cyc.item()
        if self.perceptual is not None:
            l_p = self.perceptual(x0_hat, x0)
            total = total + cfg.lambda_perceptual * l_p
            logs["perceptual"] = float(l_p)

        do_roll = rollout if rollout is not None else (self.training and float(_rand((1,), "cpu", generator)) < cfg.rollout_prob)
        if do_roll and cfg.lambda_rollout > 0:
            lo, hi = cfg.rollout_delta
            delta = torch.exp(math.log(lo) + (math.log(hi) - math.log(lo)) * _rand((B,), dev, generator))
            s = tau * (1 - delta).view(-1, 1, 1, 1)
            with torch.no_grad():
                x0_sg = x0_hat.detach().clamp(-1, 1)
                x_s = diffusion.cold_step(x_t, x0_sg, tau, s, kind, state)
            out2 = diffusion.denoise(x_s, s, kind, self_cond=x0_sg)
            l_roll = self.charbonnier(out2["x0"], x0)
            if out2["log_scale"] is not None and cfg.lambda_unc > 0:
                l_roll = l_roll + cfg.lambda_unc * self.beta_laplace_nll(out2["x0"], x0, out2["log_scale"])
            total = total + cfg.lambda_rollout * l_roll
            logs["rollout"] = l_roll.item()

        est = None
        if cfg.lambda_clock > 0:
            est = diffusion.clock_estimator(x_t.detach())
            mu, ls = est["tau_mu"], est["tau_logscale"]
            l_clk = self.beta_laplace_nll(mu, tau, ls) + F.l1_loss(mu, tau) + cfg.clock_tv_weight * self.total_variation(mu)
            total = total + cfg.lambda_clock * l_clk
            logs["clock"] = l_clk.item()
            logs["clock_mae"] = (mu.detach() - tau).abs().mean().item()
            if cfg.degradation_type == "mixed" and cfg.lambda_type > 0:
                l_type = F.cross_entropy(est["type_logits"], kind)
                total = total + cfg.lambda_type * l_type
                logs["type"] = l_type.item()
                logs["type_acc"] = (est["type_logits"].argmax(1) == kind).float().mean().item()

        logs["total"] = total.item()
        with torch.no_grad():
            logs["psnr"] = psnr(x0_hat, x0).mean().item()
        extras = {"x0": x0.detach(), "x_t": x_t.detach(), "x0_hat": x0_hat.detach(), "tau": tau.detach(), "kind": kind,
                  "log_scale": out["log_scale"].detach() if out["log_scale"] is not None else None,
                  "tau_hat": est["tau_mu"].detach() if est is not None else None}
        return total, logs, extras


