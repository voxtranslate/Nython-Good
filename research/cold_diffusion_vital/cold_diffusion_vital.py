        axes[1].set_title("|x0_hat - x0|")
        for a in axes[:2]:
            a.axis("off")
        axes[2].plot(xs, ys, "o-", label="model")
        lim = max(xs + ys + [1e-3])
        axes[2].plot([0, lim], [0, lim], "k--", label="calibrated (E|e| = b)")
        axes[2].set_xlabel("predicted b")
        axes[2].set_ylabel("mean |error|")
        axes[2].legend()
        axes[2].grid(True, alpha=0.3)
        r = pearson(b, err)
        axes[2].set_title(f"Reliability diagram (r = {r:.2f})")
        plt.tight_layout()
        fig.savefig(save_dir / "uncertainty.png", dpi=150)
        plt.close(fig)
        return {"pearson_error_uncertainty": r, "mean_b": float(b.mean()), "mean_abs_error": float(err.mean())}

