IMAGE_EXTENSIONS = (".jpg", ".jpeg", ".png", ".bmp", ".tif", ".tiff", ".webp")


def list_images(folder: Union[str, Path]) -> List[Path]:
    folder = Path(folder)
    if not folder.exists():
        return []
    return sorted(p for p in folder.rglob("*") if p.suffix.lower() in IMAGE_EXTENSIONS)


class ImageDataset(Dataset):
    """Folder of clean images -> dict(image in [-1, 1], path, idx)."""

    def __init__(self, data_dir: str, image_size: Tuple[int, int] = (256, 256),
                 split: str = "train", augment: bool = True, max_images: int = 0):
        super().__init__()
        self.data_dir = Path(data_dir)
        self.image_size = tuple(image_size)
        self.split = split
        self.augment = augment
        self.image_paths = list_images(self.data_dir)
        if max_images and max_images > 0:
            self.image_paths = self.image_paths[:max_images]
        if not self.image_paths:
            raise ValueError(f"No images found in {data_dir}")
        print(f"Found {len(self.image_paths)} images in {data_dir}")
        self.transform = self._build_transforms()

    def _build_transforms(self):
        normalize = transforms.Normalize(mean=[0.5, 0.5, 0.5], std=[0.5, 0.5, 0.5])
        if self.split == "train" and self.augment:
            return transforms.Compose([
                transforms.RandomResizedCrop(self.image_size, scale=(0.6, 1.0), antialias=True),
                transforms.RandomHorizontalFlip(),
                transforms.RandomApply([transforms.ColorJitter(0.1, 0.1, 0.1, 0.03)], p=0.3),
                transforms.ToTensor(),
                normalize,
            ])
        return transforms.Compose([
            transforms.Resize(min(self.image_size), antialias=True),  # keeps the aspect ratio
            transforms.CenterCrop(self.image_size),
            transforms.ToTensor(),
            normalize,
        ])

    def __len__(self):
        return len(self.image_paths)

    def __getitem__(self, idx):
        # Bounded retry instead of unbounded recursion on corrupt files.
        for attempt in range(10):
            j = idx if attempt == 0 else np.random.randint(0, len(self))
            try:
                img_path = self.image_paths[j]
                image = Image.open(img_path).convert("RGB")
                return {"image": self.transform(image), "path": str(img_path), "idx": j}
            except Exception as e:  # noqa: BLE001
                print(f"Error loading image {self.image_paths[j]}: {e}")
        raise RuntimeError("Too many unreadable images in a row.")


class SyntheticImageDataset(Dataset):
    """
    Procedural images (shapes, edges, stripes, gradients, text-like strokes). Deterministic per
    index. Used as a fallback so the whole pipeline (training, resume, inference and
    interpretability) can be smoke-tested without the Kaggle folders.
    """

    def __init__(self, num_images: int, image_size: Tuple[int, int] = (256, 256), seed: int = 0):
        self.n = num_images
        self.image_size = tuple(image_size)
        self.seed = seed

    def __len__(self):
        return self.n

    def __getitem__(self, idx):
        rng = np.random.RandomState(self.seed * 100003 + idx)
        H, W = self.image_size
        yy, xx = np.mgrid[0:H, 0:W].astype(np.float32)
        c0, c1 = rng.rand(3), rng.rand(3)
        ang = rng.rand() * np.pi
        g = (np.cos(ang) * xx / W + np.sin(ang) * yy / H)
        g = (g - g.min()) / (np.ptp(g) + 1e-6)
        base = (c0[None, None] * (1 - g[..., None]) + c1[None, None] * g[..., None])
        if rng.rand() < 0.6:  # stripes / texture
            f = rng.uniform(4, 40)
            th = rng.rand() * np.pi
            stripes = 0.5 + 0.5 * np.sin(2 * np.pi * f * (np.cos(th) * xx / W + np.sin(th) * yy / H))
            base = base * (0.75 + 0.25 * stripes[..., None])
        img = Image.fromarray((np.clip(base, 0, 1) * 255).astype(np.uint8))
        draw = ImageDraw.Draw(img)
        for _ in range(rng.randint(3, 10)):
            col = tuple(int(v) for v in rng.randint(0, 256, 3))
            x0_, y0_ = rng.randint(0, W), rng.randint(0, H)
            x1_, y1_ = x0_ + rng.randint(8, W // 2), y0_ + rng.randint(8, H // 2)
            kind = rng.randint(0, 3)
            if kind == 0:
                draw.ellipse([x0_, y0_, x1_, y1_], fill=col)
            elif kind == 1:
                draw.rectangle([x0_, y0_, x1_, y1_], fill=col)
            else:
                draw.line([x0_, y0_, x1_, y1_], fill=col, width=int(rng.randint(1, 5)))
        t = torch.from_numpy(np.asarray(img, dtype=np.float32) / 255.0).permute(2, 0, 1)
        return {"image": t * 2 - 1, "path": f"synthetic_{idx:05d}", "idx": idx}


def build_datasets(cfg: Config) -> Tuple[Dataset, Dataset]:
    """Returns (train, val). Falls back to procedural data if the folders are missing."""
    try:
        train = ImageDataset(cfg.train_data_dir, cfg.image_size, "train", cfg.augment, cfg.max_train_images)
        val = ImageDataset(cfg.val_data_dir, cfg.image_size, "val", False, cfg.max_val_images)
        return train, val
    except ValueError as e:
        if not cfg.synthetic_fallback:
            raise
        print(f"[data] {e} -> using SyntheticImageDataset fallback.")
        return (SyntheticImageDataset(cfg.synthetic_num_train, cfg.image_size, seed=cfg.seed),
                SyntheticImageDataset(cfg.synthetic_num_val, cfg.image_size, seed=cfg.seed + 1))


def load_image_tensor(path: Union[str, Path], max_side: int = 0) -> Tuple[torch.Tensor, Tuple[int, int]]:
    """Loads an arbitrary-size RGB image as (1, 3, H, W) in [-1, 1]; returns it and the original (W, H)."""
    img = Image.open(path).convert("RGB")
    orig = img.size
    if max_side and max(img.size) > max_side:
        s = max_side / max(img.size)
        img = img.resize((max(8, int(img.width * s)), max(8, int(img.height * s))), Image.BICUBIC)
    t = transforms.ToTensor()(img) * 2 - 1
    return t.unsqueeze(0), orig


