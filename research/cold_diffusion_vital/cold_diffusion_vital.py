def build_model(cfg: Config) -> ColdDiffusionModel:
    return ColdDiffusionModel(ViTAL.from_config(cfg), cfg)


def main(cfg: Optional[Config] = None):
    """Train (auto-resuming), then run every inference / interpretability capability.
    No argparse / sys: edit `Config` (or pass a Config instance)."""
    print("=" * 78)
    print("ViTAL-CF  |  Clock-Field Cold Diffusion - Training & Inference Pipeline")
    print("=" * 78)
    cfg = cfg or Config()
    seed_everything(cfg.seed, cfg.deterministic)
    cfg.save(Path(cfg.checkpoint_dir) / "config.json")
    print("\nConfiguration:")
    for k, v in cfg.to_dict().items():
        print(f"  {k}: {v}")

    print("\n" + "-" * 78)
    print("Creating ViTAL-CF model...")
    model = build_model(cfg)
    print(f"  backbone (ViTAL)          : {count_parameters(model.model):,} parameters")
    print(f"  spectral clock estimator  : {count_parameters(model.clock_estimator):,} parameters")
    print(f"  total                     : {count_parameters(model):,} parameters")

    print("\nCreating datasets...")
    train_dataset, val_dataset = build_datasets(cfg)
    print(f"Train dataset: {len(train_dataset)} images | Val dataset: {len(val_dataset)} images")

    print("\nCreating trainer (auto-resumes from the latest checkpoint if present)...")
    trainer = Trainer(model=model, train_dataset=train_dataset, val_dataset=val_dataset, config=cfg)

    print("\n" + "=" * 78)
    print("Starting Training...")
    print("=" * 78)
    try:
        trainer.train()
        print("\nTraining completed successfully!")
    except KeyboardInterrupt:
        print("\nTraining interrupted by user - saving an 'interrupted' checkpoint (resume will redo this epoch).")
        trainer.save_checkpoint(epoch_complete=False)
    except Exception as e:  # noqa: BLE001
        print(f"\nTraining failed with error: {e}")
        traceback.print_exc()
        trainer.save_checkpoint(epoch_complete=False)

    print("\n" + "=" * 78)
    print("Running Inference...")
    print("=" * 78)
    deploy = trainer.ema.model if trainer.ema is not None else trainer.model
    inferencer = Inferencer(model=deploy, config=cfg, checkpoint="auto", use_ema=True)
    test_dataset: Dataset = val_dataset
    if cfg.test_data_dir and list_images(cfg.test_data_dir):
        test_dataset = ImageDataset(cfg.test_data_dir, cfg.image_size, "val", False, cfg.max_val_images)
    real_images = list_images(cfg.real_images_dir) if cfg.real_images_dir else []
    inferencer.run_all(test_dataset, real_images)

    final_model_path = Path(cfg.checkpoint_dir) / "final_model.pt"
    example = next(iter(DataLoader(test_dataset, batch_size=2, shuffle=False)))["image"]
    torch.save({"model_state_dict": deploy.state_dict(), "config": cfg.to_dict(), "inference_examples": example.cpu()},
               final_model_path)
    print("\n" + "=" * 78)
    print("Pipeline completed successfully!")
    print("=" * 78)
    print(f"Final model saved to : {final_model_path}")
    print(f"Checkpoints          : {cfg.checkpoint_dir}")
    print(f"Training curves      : {Path(cfg.checkpoint_dir) / 'training_curves.png'}")
    print(f"Inference outputs    : {Path(cfg.output_dir) / 'inference'}")
    return model, trainer, inferencer


def deblur_image_pipeline(model_path: str, image_path: str, output_dir: Optional[str] = None, strength: float = 1.0,
                          device: Optional[str] = None) -> torch.Tensor:
    """Stand-alone blind restoration of one image with a trained checkpoint (best/latest/final)."""
    print("Starting Deblurring Pipeline...")
    ckpt = torch.load(model_path, map_location="cpu", weights_only=False)
    cfg = Config.from_dict(ckpt["config"], device=device or ("cuda" if torch.cuda.is_available() else "cpu"))
    model = build_model(cfg)
    inferencer = Inferencer(model, cfg, checkpoint=model_path, use_ema=True)
    save_dir = Path(output_dir) if output_dir else None
    return inferencer.restore_real_image(image_path, save_dir=save_dir, strength=strength)["output"]


