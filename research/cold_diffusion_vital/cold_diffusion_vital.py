        demo_loader = DataLoader(dataset, batch_size=min(cfg.infer_num_images, len(dataset)), shuffle=False, num_workers=0)
        demo = next(iter(demo_loader))["image"]

        summary["evaluation"] = self._safe("evaluate", lambda: self.evaluate(eval_loader))

        def _demo(blind: bool):
            d = self._dir("demo_blind" if blind else "demo_known_clock")
            res = self.infer(demo, tau="field", sampler=cfg.sampler, blind=blind, record=True, generator=self._gen(3))
            self.visualize_results(res, save_path=str(d / "inference_results.png"))
            save_image(make_grid(torch.cat([to01(res["input"]), to01(res["degraded"]), to01(res["output"])]).cpu(),
                                 nrow=res["input"].shape[0], padding=2), d / "clean_degraded_restored.png")
            save_json(res["metrics"], d / "metrics.json")
            print(f"[demo {'blind' if blind else 'known clock'}] {res['metrics']}")
            return res["metrics"]

        summary["demo_known_clock"] = self._safe("demo", lambda: _demo(False))
        summary["demo_blind"] = self._safe("demo_blind", lambda: _demo(True))
        summary["clock_estimator"] = self._safe("evaluate_clock", lambda: self.evaluate_clock(eval_loader))
        summary["interpretability"] = self._safe("interpret", lambda: self.interpret(demo[:1], tau="field"))
        summary["generation"] = self._safe("generate", lambda: (self.generate_samples(fit_loader=eval_loader) is not None))

        # "Real image" example: a clean validation image with a spatially varying (defocus-like) blur,
        # written to disk and restored *blindly* from the file, then compared with the ground truth.
        def _real_demo():
            d = self._dir("real_demo")
            g = self._gen(11)
            x0 = demo[:1].to(self.device).float()
            _, _, H, W = x0.shape
            kind = torch.full((1,), BLUR if cfg.degradation_type == "mixed" else KINDS.index(cfg.degradation_type),
                              dtype=torch.long, device=self.device)
            tau = self.model.sample_tau(1, H, W, self.device, g, force_field=True)
            y, _ = self.model.degradation.apply(x0, tau, kind, generator=g)
            y = self._observe(y, g)
            demo_path = d / "demo_degraded_image.png"
            tensor_to_pil(y).save(demo_path)
            tensor_to_pil(x0).save(d / "demo_ground_truth.png")
            save_image(colorize(tau[0, 0], "viridis", 0, 1), d / "demo_true_clock.png")
            print(f"Using demo image: {demo_path}")
            r = self.restore_real_image(demo_path, save_dir=d / "restoration", gt=d / "demo_ground_truth.png")
            self._safe("strength_sweep", lambda: self.strength_sweep(demo_path, save_dir=self._dir("real_demo", "strength_sweep")))
            return r["metrics"]

        summary["real_demo"] = self._safe("real_demo", _real_demo)
        if real_image_paths:
            summary["real_images"] = [self._safe(f"real:{p}", lambda p=p: self.restore_real_image(p)["metrics"])
                                      for p in list(real_image_paths)[:cfg.infer_num_images]]
        save_json(summary, self.root / "inference_summary.json")
        print(f"\nAll inference outputs are in {self.root}")
        return summary


