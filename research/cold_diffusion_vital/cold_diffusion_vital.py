"""
===========================================================================================
ViTAL-CF : Clock-Field Cold Diffusion with the ViTAL backbone (no VQ)
===========================================================================================

A deterministic ("cold") diffusion model for image restoration (deblurring first, and also
denoising / inpainting / pixelation and an all-in-one "mixed" mode) plus unconditional
generation from a degraded prior.

Layout of this file
-------------------
    SECTION 0  Imports
    SECTION 1  Configuration                      -> class Config
    SECTION 2  Utilities
    SECTION 3  Physics: exact heat operator and cold degradations
    SECTION 4  Datasets                           -> ImageDataset, SyntheticImageDataset
    SECTION 5  Model                              -> ViTAL backbone, SpectralClockEstimator,
                                                     ClockAwareSpectralGate, ColdDiffusionModel
    SECTION 6  Losses                             -> ColdDiffusionLoss
    SECTION 7  Metrics
    SECTION 8  Trainer                            -> Trainer (+ EMA)
    SECTION 9  Inferencer                         -> Inferencer
    SECTION 10 Main                               -> main(), deblur_image_pipeline()

What is new compared to cold diffusion (Bansal et al., 2022) and the rest of the literature
-------------------------------------------------------------------------------------------
Two headline contributions:

 [N1] SPECTRAL CLOCK FIELD (SCF): blind, spatially varying cold diffusion.
      The scalar diffusion time t becomes a per-pixel field tau(x) in [0, 1]. The forward
      operator is a spatially varying heat dissipation, built from an exact DCT-domain heat
      kernel bank that is interpolated per pixel. The network is conditioned on the field
      through Clock-Modulated Normalisation, a spatial FiLM computed from a per-pixel clock
      embedding.
      A Spectral Clock Estimator (SCE) reads the degradation level straight from the
      observation. Gaussian blur multiplies the spectrum by exp(-sigma^2 w^2 / 2), so the
      log-ratio of neighbouring band energies is linear in sigma^2, and the SCE uses those
      log-ratios as physics features. It predicts tau(x) together with an aleatoric
      confidence. The confidence drives a normalised-convolution smoothing of the field,
      which propagates the clock from textured areas into flat areas where blur cannot be
      identified.
      Sampling uses Synchronised Field Descent, tau_k(x) = tau_obs(x) * u_k, so every pixel
      reaches tau = 0 on the same step. By contrast, SVNR (Kawar et al. 2023) uses noise-only,
      asynchronous per-pixel times, and DynFaceRestore / SuperSharpen estimate a single
      global blur level.

 [N2] SPECTRAL RANGE-NULL COLD SAMPLER (SRN-CS).
      Bansal's improved update  x_s = x_t - D(x0_hat, t) + D(x0_hat, s)  is combined with an
      exact Fourier-domain range/null-space anchoring of x0_hat to the observation y:
          x0_hat <- x0_hat + eta * K/(K^2 + lambda) * (y - D(x0_hat, tau_obs))
      Here K is the analytic heat transfer function, with local anchors for clock fields.
      Frequencies the operator keeps (the range space) are taken from the data. Frequencies
      the operator annihilated (the null space) are generated by the network. This is the
      DDNM idea (Wang et al. 2023), moved from Gaussian diffusion to deterministic
      heat-dissipation trajectories and to spatially varying operators.

Supporting contributions (model / losses / training):
 [N3] Clock-Aware Spectral Gate (CASG): a feature-space inverse-heat filter. Its gain
      exp(c_c * tanh(a_c * sigma_f^2 |w|^2 / (2 c_c))) follows the physics of the estimated
      clock and saturates smoothly at a learned ceiling c_c. A learned residual spectral
      response is added on top, and the result is gated
      spatially by the clock field.
 [N4] Sampler-Consistent Rollout (SCR) loss: the network is also trained on the exact
      Algorithm-2 states that its own detached prediction produces. This closes the
      train/test exposure gap of cold sampling, and it supplies self-conditioning inputs for
      free (no teacher, no extra EMA network; compare the EPCT of ReCo-Diff 2026).
 [N5] Null-Space Spectral (NSS) loss: an L1 loss in the Fourier domain weighted by the
      annihilation spectrum (1 - |K_tau(w)|^2)^gamma of the actual degradation, so capacity
      goes to the frequencies the operator destroyed.
 [N6] Mean-decoupled beta-Laplace uncertainty. The uncertainty head never biases the mean.
      Its output drives the uncertainty maps, the calibration plots, and an
      uncertainty-gated stochastic refinement ("churn") in the sampler.
 [N7] Exact continuous-time Neumann heat operator (a DCT-equivalent even extension plus FFT),
      with sigma(0) = 0 exactly. This replaces the truncated 31-tap kernel, which saturated
      at large sigma and darkened the image borders.
 [N8] Degraded-prior bank for generation: a Gaussian fitted to thumbnails of maximally
      degraded images, replacing the incorrect "start from white noise" of a blur model.

Bugs of the previous version that are fixed here (the main ones)
-----------------------------------------------------------------
  * `dataclass`, `field` and `asdict` were used without being imported. The SR/GAN Config
    was never used.
  * The time was normalised twice (t/T/T), so the network received t ~ 1e-6. The
    sinusoidal embedding was also fed t in [0, 1] without scaling. Both are fixed.
  * "Importance" timestep sampling drew almost only tiny-blur steps (weights 1/sigma),
    contradicting its own comment.
  * The random mask was re-drawn on every call, so it was not a deterministic cold
    degradation and Algorithm 2 was meaningless. It now uses a fixed per-sample rank field
    with nested masks.
  * Blur kernels were truncated to 31 taps (sigma up to 30) with zero padding.
  * U-Net skips were misaligned by one resolution level (and bicubically resized). The
    full-resolution stem features were never used.
  * BatchNorm with batch size 3 inside a diffusion denoiser is replaced by GroupNorm.
  * Swin: the image is now padded before it is rolled, and masks are cached instead of
    re-registering buffers on every forward pass. The shift order now follows Swin.
  * Training metrics were overwritten after the checkpoint was loaded, so resuming lost
    the curves.
  * Validation used random timesteps, so the curves were noisy. It is now deterministic.
  * The naive (Algorithm 1) sampler was used even though the degradation is smooth.
    `sample()` started a blur model from Gaussian noise. Real-image deblurring always
    started at maximum blur and injected noise with a standard deviation of up to 1.5.
  * cv2 and glob were imported but not used; the per-sample Python loop in the forward
    degradation is removed; plt.show() is gone.

Everything runs without argparse/sys: edit `Config` (or pass one to `main(cfg)`).
"""

