class Inferencer:
    """
    Every capability of the model, plus everything needed to understand it.

    Capabilities
      * infer / evaluate        synthetic restoration with known or estimated clock, all samplers,
                                PSNR / SSIM / LPIPS / Null-Space Recovery, quality vs degradation
      * restore_real_image      blind restoration of real photos (estimated clock field, strength control)
      * strength_sweep          controllable restoration strength (tau_obs * kappa)
      * generate_samples        unconditional generation from the degraded prior
      * evaluate_clock          accuracy and calibration of the Spectral Clock Estimator

    Interpretability (interpret)
      trajectories (strip + GIF + per-step PSNR/uncertainty), Swin attention maps and per-head
      attention distance/entropy, encoder/decoder feature PCA, spectral-gate gain curves vs.
      the physical inverse-heat gain, range/null-space decomposition of the output,
      radial power spectra, uncertainty maps + reliability diagram, clock-sensitivity map
      d x0_hat / d tau, estimated vs true clock field, physics features of the estimator,
      raw tensors (.pt) and JSON summaries.
    """

    def __init__(self, model: ColdDiffusionModel, config: Config, device: Optional[str] = None,
                 checkpoint: Optional[str] = "auto", use_ema: bool = True):
        self.cfg = config
        self.device = torch.device(device or config.device)
        self.model = model.to(self.device).eval()
        self.loaded_from: Optional[str] = None
        if checkpoint:
            self.load_checkpoint(checkpoint, use_ema)
        self.root = Path(config.output_dir) / "inference"
        self.root.mkdir(parents=True, exist_ok=True)
        self.lpips = LPIPSMetric(self.device) if (config.compute_lpips and PYIQA_AVAILABLE) else None

    # ---- loading -------------------------------------------------------------------------------
    def load_checkpoint(self, checkpoint: str = "auto", use_ema: bool = True):
        ck_dir = Path(self.cfg.checkpoint_dir)
        if checkpoint == "auto":
            cands = [ck_dir / "checkpoint_best.pt", ck_dir / "checkpoint_latest.pt", ck_dir / "final_model.pt"]
            path = next((p for p in cands if p.exists()), None)
            if path is None:
                print("[inferencer] no checkpoint found - using the in-memory weights.")
                return
        else:
            path = Path(checkpoint)
        ck = torch.load(path, map_location=self.device, weights_only=False)
        if use_ema and ck.get("ema_state_dict") is not None:
            sd, which = ck["ema_state_dict"], "EMA"
        else:
            sd, which = ck.get("model_state_dict", ck), "raw"
        res = self.model.load_state_dict(sd, strict=False)
        if res.missing_keys or res.unexpected_keys:
            print(f"[inferencer] missing={len(res.missing_keys)} unexpected={len(res.unexpected_keys)} keys")
        self.loaded_from = str(path)
        print(f"[inferencer] loaded {which} weights from {path}")

    # ---- helpers -------------------------------------------------------------------------------
    def _gen(self, offset: int = 0) -> torch.Generator:
        return torch.Generator().manual_seed(self.cfg.seed + 2024 + offset)

    def _dir(self, *parts) -> Path:
        d = self.root.joinpath(*parts)
        d.mkdir(parents=True, exist_ok=True)
        return d

    @staticmethod
    def _safe(name: str, fn):
        try:
            return fn()
        except Exception as e:  # noqa: BLE001
            print(f"[inferencer] '{name}' failed: {e}")
            traceback.print_exc()
            return None

    def _tau_map(self, tau, B, H, W, generator) -> torch.Tensor:
        if isinstance(tau, torch.Tensor):
            t = tau.to(self.device).float()
            return t.view(B, 1, 1, 1).expand(B, 1, H, W).contiguous() if t.dim() == 1 else t
        if tau == "field":
            return self.model.sample_tau(B, H, W, self.device, generator, force_field=True)
        return torch.full((B, 1, H, W), float(tau), device=self.device)

    def _observe(self, y: torch.Tensor, generator: Optional[torch.Generator]) -> torch.Tensor:
        """Realistic synthetic observation: sensor noise + 8-bit quantisation. Without it an exact,
        noiseless, known operator can be inverted perfectly (the 'inverse crime')."""
        if self.cfg.eval_obs_noise > 0:
            y = y + self.cfg.eval_obs_noise * _randn(tuple(y.shape), y.device, generator)
        if self.cfg.eval_quantize:
            y = torch.round(to01(y) * 255.0) / 255.0 * 2 - 1
        return y.clamp(-1, 1)

    def _metrics(self, out, x0, y, tau, kind) -> Dict[str, float]:
        m = {"psnr": psnr(out, x0).mean().item(), "ssim": ssim(out, x0).mean().item(),
             "psnr_input": psnr(y, x0).mean().item(), "ssim_input": ssim(y, x0).mean().item(),
             "nsr": null_space_recovery(out, x0, y, tau, kind, self.model.degradation).mean().item()}
        if self.lpips is not None:
            v = self.lpips(out, x0)
            if v is not None:
                m["lpips"] = v.mean().item()
        return m

    # ---- capability 1: synthetic restoration -------------------------------------------------------
    @torch.no_grad()
    def infer(self, images: torch.Tensor, tau: Union[float, str, torch.Tensor] = "field", kind: Optional[torch.Tensor] = None,
              sampler: Optional[str] = None, steps: Optional[int] = None, blind: bool = False, record: bool = True,
              generator: Optional[torch.Generator] = None) -> Dict[str, Any]:
        """Degrade clean images with a known clock, restore them (known or blind clock), measure."""
        g = generator or self._gen()
        x0 = images.to(self.device).float()
        B, C, H, W = x0.shape
        if kind is None:
            kind = self.model.sample_kind(B, self.device, g)
        tau_map = self._tau_map(tau, B, H, W, g)
        y, st = self.model.degradation.apply(x0, tau_map, kind, generator=g)
        y = self._observe(y, g)
        observed = st["rank"] >= self.model.degradation.mask_ratio(tau_map)
        t0 = time.time()
        res = self.model.restore(y, tau_obs=None if blind else tau_map, kind=None if blind else kind, sampler=sampler,
                                 steps=steps, record=record, observed=observed, generator=g, x0_gt=x0)
        res["time"] = time.time() - t0
        res.update({"input": x0, "degraded": y, "tau_true": tau_map, "kind_true": kind, "blind": blind})
        res["metrics"] = self._metrics(res["output"], x0, y, tau_map, kind)
        return res

    @torch.no_grad()
    def evaluate(self, loader: DataLoader, samplers: Optional[Sequence[str]] = None, taus: Optional[Sequence[Any]] = None,
                 max_batches: Optional[int] = None, include_blind: bool = True, save_dir: Optional[Path] = None) -> Dict[str, Any]:
        """Benchmark every sampler on every degradation level (identical degradations per sampler)."""
        cfg = self.cfg
        samplers = list(samplers or cfg.eval_samplers)
        taus = list(taus or cfg.eval_taus) + ["field"]
        max_batches = max_batches or cfg.eval_max_batches
        save_dir = save_dir or self._dir("evaluation")
        methods = [(s, False) for s in samplers] + ([("srn", True)] if include_blind else [])
        rows = []
        for bi, batch in enumerate(tqdm(loader, desc="Evaluation", total=min(len(loader), max_batches))):
            if bi >= max_batches:
                break
            x0 = batch["image"]
            for ti, tv in enumerate(taus):
                seed_off = 1000 * bi + ti
                for s, blind in methods:
                    res = self.infer(x0, tau=tv, sampler=s, blind=blind, record=False, generator=self._gen(seed_off))
                    rows.append({"batch": bi, "tau": str(tv), "method": s + ("-blind" if blind else ""), "steps": res["steps"],
                                 "sec_per_image": res["time"] / x0.shape[0], **res["metrics"]})
        if not rows:
            return {}
        keys = sorted({k for r in rows for k in r if k not in ("batch", "tau", "method")})
        summary: Dict[str, Dict[str, Dict[str, float]]] = {}
        for r in rows:
            summary.setdefault(r["method"], {}).setdefault(r["tau"], {k: [] for k in keys})
            for k in keys:
                if k in r:
                    summary[r["method"]][r["tau"]][k].append(r[k])
        summary = {m: {t: {k: float(np.mean(v)) for k, v in d.items() if v} for t, d in td.items()} for m, td in summary.items()}
        with open(save_dir / "evaluation_raw.csv", "w", newline="") as f:
            w = csv.DictWriter(f, fieldnames=["batch", "tau", "method"] + keys)
            w.writeheader()
            w.writerows(rows)
        save_json(summary, save_dir / "evaluation_summary.json")

        # quality vs. degradation plot
        fig, axes = plt.subplots(1, 3, figsize=(18, 4.8))
        num_taus = [t for t in taus if t != "field"]
        for ax, metric, title in zip(axes, ("psnr", "ssim", "nsr"), ("PSNR (dB)", "SSIM", "Null-space recovery [0-1]")):
            first = next(iter(summary.values()))
            if metric != "nsr":
                ax.plot(num_taus, [first[str(t)][f"{metric}_input"] for t in num_taus], "k:", marker="x", label="degraded input")
            for m, td in summary.items():
                ax.plot(num_taus, [td[str(t)].get(metric, np.nan) for t in num_taus], marker="o", label=m)
            ax.set_xlabel("clock tau (degradation level)")
            ax.set_title(title)
            ax.grid(True, alpha=0.3)
            ax.legend(fontsize=8)
        plt.tight_layout()
        fig.savefig(save_dir / "quality_vs_degradation.png", dpi=150)
        plt.close(fig)

        print("\nEvaluation summary (PSNR / SSIM / NSR):")
        header = "method".ljust(16) + "".join(str(t).rjust(22) for t in taus)
        print(header)
        for m, td in summary.items():
            line = m.ljust(16)
            for t in taus:
                d = td.get(str(t), {})
                line += f"{d.get('psnr', np.nan):7.2f}/{d.get('ssim', np.nan):.3f}/{d.get('nsr', np.nan):5.2f}".rjust(22)
            print(line)
        return summary

    # ---- capability 2: blind restoration of real images -----------------------------------------------
    @torch.no_grad()
    def restore_real_image(self, image_path: Union[str, Path], save_dir: Optional[Path] = None, strength: float = 1.0,
                           sampler: Optional[str] = None, steps: Optional[int] = None,
                           gt: Optional[Union[str, Path, torch.Tensor]] = None) -> Dict[str, Any]:
        """Blind restoration: the Spectral Clock Estimator reads tau(x) from the photo itself."""
        image_path = Path(image_path)
        save_dir = save_dir or self._dir("real", image_path.stem)
        save_dir.mkdir(parents=True, exist_ok=True)
        y, orig_size = load_image_tensor(image_path, self.cfg.real_max_side)
        y = y.to(self.device)
        res = self.model.restore(y, tau_obs=None, kind=None, sampler=sampler, steps=steps, strength=strength,
                                 lam=self.cfg.rn_lambda_real, record=True, generator=self._gen())
        out = res["output"]
        save_image(to01(y), save_dir / "input.png")
        save_image(to01(out), save_dir / "restored.png")
        full = tensor_to_pil(out)
        if full.size != orig_size:
            full = full.resize(orig_size, Image.LANCZOS)
        full.save(save_dir / "restored_fullres.png")
        clock = res.get("clock", {})
        maps = {"clock_field": colorize(res["tau_obs"][0, 0], "viridis", 0, 1)}
        if clock:
            maps["clock_raw"] = colorize(clock["tau_mu"][0, 0], "viridis", 0, 1)
            maps["clock_confidence"] = colorize(torch.exp(-clock["tau_logscale"][0, 0]), "cividis")
        if res["uncertainty"] is not None:
            maps["uncertainty"] = colorize(res["uncertainty"][0].mean(0), "inferno")
        maps["residual"] = colorize((out - y)[0].abs().mean(0), "magma")
        for k, v in maps.items():
            save_image(v, save_dir / f"{k}.png")
        if self.cfg.save_gif and res["trajectory"]:
            save_gif([to01(f[0]) for f in res["trajectory"]], save_dir / "trajectory.gif")
        metrics: Dict[str, Any] = {"image": str(image_path), "strength": strength, "steps": res["steps"],
                                   "mean_tau": float(res["tau_obs"].mean()), "max_tau": float(res["tau_obs"].max()),
                                   "mean_sigma_px": float(self.model.degradation.sigma(res["tau_obs"]).mean()),
                                   "data_consistency_l1": float((self.model.degradation.apply(out, res["tau_obs"], res["kind"])[0] - y).abs().mean())}
        if self.cfg.degradation_type == "mixed" and clock:
            probs = clock["type_logits"].softmax(1)[0]
            metrics["type_probs"] = {KINDS[i]: float(probs[i]) for i in range(len(KINDS))}
        if gt is not None:
            gt_t = gt if isinstance(gt, torch.Tensor) else load_image_tensor(gt, self.cfg.real_max_side)[0]
            gt_t = gt_t.to(self.device).float()
            if gt_t.shape[-2:] == out.shape[-2:]:
                metrics.update({"psnr": psnr(out, gt_t).item(), "ssim": ssim(out, gt_t).item(),
                                "psnr_input": psnr(y, gt_t).item(), "ssim_input": ssim(y, gt_t).item()})
        save_json(metrics, save_dir / "metrics.json")
        self._comparison_figure([("Input", to01(y[0]), "#ff4444"), ("Restored", to01(out[0]), "#00ff88"),
                                 ("Estimated clock tau(x)", maps["clock_field"], "#44aaff"),
                                 ("Uncertainty", maps.get("uncertainty", maps["residual"]), "#ffaa00")],
                                "Blind restoration with Clock-Field Cold Diffusion", save_dir / "comparison.png")
        self._spectra_figure({"input": y, "restored": out}, save_dir / "radial_spectra.png")
        print(f"[real] {image_path.name}: mean tau {metrics['mean_tau']:.3f} (sigma~{metrics['mean_sigma_px']:.2f}px), "
              f"{res['steps']} steps -> {save_dir}" + (f" | PSNR {metrics['psnr']:.2f} dB" if "psnr" in metrics else ""))
        res["metrics"] = metrics
        return res

    def deblur_real_image(self, image_path: str, save_path: Optional[str] = None) -> torch.Tensor:
        """Backwards-compatible name of the old API."""
        save_dir = Path(save_path).with_suffix("") if save_path else None
        return self.restore_real_image(image_path, save_dir=save_dir)["output"]

    @torch.no_grad()
    def strength_sweep(self, image: Union[str, Path, torch.Tensor], strengths: Optional[Sequence[float]] = None,
                       save_dir: Optional[Path] = None) -> Dict[float, torch.Tensor]:
        """Restoration-strength control: tau_obs = kappa * tau_hat."""
        strengths = list(strengths or self.cfg.strength_sweep)
        save_dir = save_dir or self._dir("strength_sweep")
        y = load_image_tensor(image, self.cfg.real_max_side)[0] if not isinstance(image, torch.Tensor) else image
        y = y.to(self.device).float()
        outs = {}
        for s in strengths:
            outs[s] = self.model.restore(y, strength=s, lam=self.cfg.rn_lambda_real, generator=self._gen())["output"]
        grid = make_grid(torch.cat([to01(y)] + [to01(outs[s]) for s in strengths]).cpu(), nrow=len(strengths) + 1, padding=2)
        save_image(grid, save_dir / "strength_sweep.png")
        panels = [("input", to01(y[0]), "#ff4444")] + [(f"kappa = {s}", to01(outs[s][0]), "#00ff88") for s in strengths]
        self._comparison_figure(panels, "Controllable restoration strength", save_dir / "strength_sweep_figure.png")
        return outs

    # ---- capability 3: generation -----------------------------------------------------------------------
    @torch.no_grad()
    def generate_samples(self, num_samples: Optional[int] = None, image_size: Optional[Tuple[int, int]] = None,
                         steps: Optional[int] = None, save_dir: Optional[Path] = None,
                         fit_loader: Optional[DataLoader] = None) -> Optional[torch.Tensor]:
        num_samples = num_samples or self.cfg.generate_num
        image_size = tuple(image_size or self.cfg.image_size)
        save_dir = Path(save_dir) if save_dir else self._dir("generated")
        save_dir.mkdir(parents=True, exist_ok=True)
        if float(self.model.prior_ready.item()) < 0.5:
            if fit_loader is None or not self.model.fit_prior(fit_loader, self.device):
                print("[generate] no degraded prior available - skipped.")
                return None
        print(f"Generating {num_samples} samples...")
        res = self.model.generate(num_samples, image_size, steps=steps, record=True, generator=self._gen(7))
        samples = res["output"]
        for i in range(num_samples):
            save_image(to01(samples[i]), save_dir / f"generated_sample_{i:03d}.png")
        nrow = min(4, num_samples)
        save_image(make_grid(to01(samples).cpu(), nrow=nrow, padding=2), save_dir / "generated_grid.png")
        save_image(make_grid(to01(res["prior_sample"]).cpu(), nrow=nrow, padding=2), save_dir / "prior_samples_grid.png")
        self._trajectory_strip(res, save_dir / "generation_trajectory.png", idx=0)
        if self.cfg.save_gif and res["trajectory"]:
            save_gif([to01(f[0]) for f in res["trajectory"]], save_dir / "generation.gif")
        print(f"Samples saved to {save_dir}")
        return samples

    # ---- capability 4: clock estimator evaluation ----------------------------------------------------------
    @torch.no_grad()
    def evaluate_clock(self, loader: DataLoader, max_batches: Optional[int] = None, save_dir: Optional[Path] = None) -> Dict[str, Any]:
        save_dir = save_dir or self._dir("clock_estimator")
        max_batches = max_batches or self.cfg.eval_max_batches
        taus = list(self.cfg.eval_taus) + ["field"]
        t_true, t_raw, t_smooth, err_abs, pred_scale = [], [], [], [], []
        per_tau: Dict[str, List[float]] = {}
        correct, total = 0, 0
        for bi, batch in enumerate(loader):
            if bi >= max_batches:
                break
            x0 = batch["image"].to(self.device).float()
            B, C, H, W = x0.shape
            for ti, tv in enumerate(taus):
                g = self._gen(5000 + 1000 * bi + ti)
                kind = self.model.sample_kind(B, self.device, g)
                tau = self._tau_map(tv, B, H, W, g)
                y, _ = self.model.degradation.apply(x0, tau, kind, generator=g)
                est = self.model.estimate_clock(self._observe(y, g))
                sub = (slice(None), slice(None), slice(None, None, 8), slice(None, None, 8))
                t_true.append(tau[sub].flatten().cpu())
                t_raw.append(est["tau_mu"][sub].flatten().cpu())
                t_smooth.append(est["tau_smooth"][sub].flatten().cpu())
                err_abs.append((est["tau_mu"] - tau)[sub].abs().flatten().cpu())
                pred_scale.append(est["tau_logscale"][sub].exp().flatten().cpu())
                per_tau.setdefault(str(tv), []).append((est["tau_smooth"] - tau).abs().mean().item())
                correct += int((est["type_logits"].argmax(1) == kind).sum())
                total += B
        if not t_true:
            return {}
        tt, tr, ts = torch.cat(t_true), torch.cat(t_raw), torch.cat(t_smooth)
        ea, ps = torch.cat(err_abs), torch.cat(pred_scale)
        out = {"mae_raw": float((tr - tt).abs().mean()), "mae_smoothed": float((ts - tt).abs().mean()),
               "mae_per_tau": {k: float(np.mean(v)) for k, v in per_tau.items()},
               "uncertainty_error_pearson": pearson(ps, ea)}
        if self.cfg.degradation_type == "mixed":
            out["type_accuracy"] = correct / max(total, 1)
        save_json(out, save_dir / "clock_metrics.json")
        fig, axes = plt.subplots(1, 3, figsize=(17, 5))
        axes[0].hexbin(tt.numpy(), ts.numpy(), gridsize=40, cmap="viridis", mincnt=1)
        axes[0].plot([0, 1], [0, 1], "r--")
        axes[0].set_xlabel("true tau")
        axes[0].set_ylabel("estimated tau (smoothed)")
        axes[0].set_title(f"Spectral Clock Estimator  MAE={out['mae_smoothed']:.3f}")
        ks = list(out["mae_per_tau"].keys())
        axes[1].bar(ks, [out["mae_per_tau"][k] for k in ks], color="#44aaff")
        axes[1].set_title("MAE per degradation level")
        q = torch.quantile(ps, torch.linspace(0, 1, 11))
        xs, ys = [], []
        for i in range(10):
            m = (ps >= q[i]) & (ps <= q[i + 1])
            if m.any():
                xs.append(float(ps[m].mean()))
                ys.append(float(ea[m].mean()))
        axes[2].plot(xs, ys, "o-", label="estimator")
        lim = max(xs + ys + [1e-3])
        axes[2].plot([0, lim], [0, lim], "k--", label="perfect (Laplace: E|e| = b)")
        axes[2].set_xlabel("predicted scale b")
        axes[2].set_ylabel("mean |error|")
        axes[2].set_title(f"Clock uncertainty calibration (r={out['uncertainty_error_pearson']:.2f})")
        axes[2].legend()
        for a in axes:
            a.grid(True, alpha=0.3)
        plt.tight_layout()
        fig.savefig(save_dir / "clock_estimator.png", dpi=150)
        plt.close(fig)
        print(f"[clock] MAE raw {out['mae_raw']:.4f} | smoothed {out['mae_smoothed']:.4f} | "
              f"uncertainty/error r = {out['uncertainty_error_pearson']:.3f}")
        return out

