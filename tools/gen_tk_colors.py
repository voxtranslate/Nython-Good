"""gen_tk_colors.py - lib/_tkinter/colors.ny from X.Org's rgb.txt (round 84).

    python3 tools/gen_tk_colors.py /usr/share/X11/rgb.txt lib/_tkinter/colors.ny

Tk's xcolors.c is the same list plus the eight web colours TIP 403 added in
Tk 8.6 (aqua, crimson, fuchsia, indigo, lime, olive, silver, teal); gray,
green, maroon and purple keep their X11 values, as in Tk.
"""
import sys
src = sys.argv[1]
out = sys.argv[2]
names = {}
for line in open(src):
    if line.startswith("!") or not line.strip():
        continue
    parts = line.split(None, 3)
    r, g, b = int(parts[0]), int(parts[1]), int(parts[2])
    name = parts[3].strip()
    key = name.replace(" ", "").lower()
    names.setdefault(key, (r, g, b))
for k, v in (("aqua", (0, 255, 255)), ("crimson", (220, 20, 60)), ("fuchsia", (255, 0, 255)),
             ("indigo", (75, 0, 130)), ("lime", (0, 255, 0)), ("olive", (128, 128, 0)),
             ("silver", (192, 192, 192)), ("teal", (0, 128, 128))):
    names.setdefault(k, v)
items = sorted(names.items())
with open(out, "w") as f:
    f.write("# nython: module    (part of the _tkinter package: lib/_tkinter/)\n")
    f.write("# lib/_tkinter/colors.ny - the X11 colour names Tk knows (round 84).\n")
    f.write("#\n")
    f.write("# Generated by tools/gen_tk_colors.py from X.Org's rgb.txt, the list Tk's\n")
    f.write("# xcolors.c is made from, plus TIP 403's web colours: %d names, keyed\n" % len(items))
    f.write("# lowercase without spaces (Tk looks names up ignoring case, and\n")
    f.write("# \"alice blue\" is \"AliceBlue\").  The\n")
    f.write("# value packs red, green and blue into one int (0xRRGGBB).\n\n")
    f.write("COLORS = {\n")
    for k, (r, g, b) in items:
        f.write('    "%s": 0x%02x%02x%02x,\n' % (k, r, g, b))
    f.write("}\n")
print(len(items))
