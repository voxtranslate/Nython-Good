#!/usr/bin/env python3
"""Generate include/NyBuiltinFns.hpp - the functions CPython implements in C,
module by module, for the modules Nython provides (round 84).

    python3 tools/gen_builtin_fns.py > include/NyBuiltinFns.hpp

Every python3.10 ... python3.13 found is asked (the union is kept): for each
module of lib/ (and the engines' own os, sys, time, gc), the public names
whose value is a builtin function of a module (`__self__` a module - not a
bound method of an instance, as random.random is).

The engines read the table when a module has run (nyrt::cpython_builtin_fns):
a plain Nython function bound under one of these names becomes a builtin
function - not bound when read through a class, type
builtin_function_or_method, shown as <built-in function name> - as the
CPython function it stands for is (the prelude's _ny_seal_cmodule).
"""
import json, os, subprocess, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LIB = os.path.join(ROOT, "lib")

PROBE = r"""
import importlib, json, sys, types, warnings
warnings.simplefilter("ignore")
out = {}
for m in json.loads(sys.argv[1]):
    try:
        M = importlib.import_module(m)
    except BaseException:
        continue
    names = []
    for n in sorted(dir(M)):
        if n.startswith("_"):
            continue
        v = getattr(M, n, None)
        if isinstance(v, types.BuiltinFunctionType) and isinstance(getattr(v, "__self__", None), types.ModuleType):
            names.append(n)
    if names:
        out[m] = names
print(json.dumps(out))
"""

# never sealed: builtins' own are natives already; these are Nython's own or
# a GUI toolkit's
SKIP = {"builtins", "antigravity", "this"}


def modules():
    mods = set()
    for f in os.listdir(LIB):
        p = os.path.join(LIB, f)
        if f.endswith(".ny") and not f.startswith("_ny"):
            mods.add(f[:-3])
        elif os.path.isdir(p) and os.path.exists(os.path.join(p, "__init__.ny")):
            mods.add(f)
            for g in os.listdir(p):
                if g.endswith(".ny") and g != "__init__.ny":
                    mods.add(f + "." + g[:-3])
    mods |= {"os", "sys", "time", "gc", "posix"}
    return sorted(mods - SKIP)


def main():
    mods = modules()
    table, seen = {}, []
    for v in ("3.10", "3.11", "3.12", "3.13"):
        exe = "/usr/bin/python" + v
        if not os.path.exists(exe):
            continue
        try:
            r = subprocess.run([exe, "-I", "-c", PROBE, json.dumps(mods)], capture_output=True, text=True, timeout=600)
            got = json.loads(r.stdout.strip().splitlines()[-1])
        except Exception:
            continue
        seen.append(v)
        for m, names in got.items():
            table.setdefault(m, set()).update(names)
    if not seen:
        sys.exit("no python3.x found")
    w = sys.stdout.write
    w("// Generated by tools/gen_builtin_fns.py from CPython " + ", ".join(seen) + " - do not edit.\n")
    w("// The functions CPython implements in C, per module Nython provides: a\n")
    w("// plain Nython function a module binds under one of these names is made a\n")
    w("// builtin function when the module has run (round 84, the prelude's\n")
    w("// _ny_seal_cmodule; HANDOFF §0w2).\n")
    w("#pragma once\n#include <string>\n#include <unordered_map>\n\nnamespace nyrt {\n")
    w("inline const char* cpython_builtin_fns(const std::string& module) {\n")
    w("    static const std::unordered_map<std::string, const char*> t = {\n")
    for m in sorted(table):
        names = " ".join(sorted(table[m]))
        line = '        {"' + m + '", "'
        w(line)
        col = len(line)
        parts, cur = [], ""
        for n in names.split(" "):
            if cur and len(cur) + len(n) + 1 > 96:
                parts.append(cur + " ")
                cur = n
            else:
                cur = n if not cur else cur + " " + n
        parts.append(cur)
        w(('"\n' + " " * (col - 1) + '"').join(parts))
        w('"},\n')
    w("    };\n    auto it = t.find(module);\n    return it == t.end() ? nullptr : it->second;\n}\n}   // namespace nyrt\n")


if __name__ == "__main__":
    main()
