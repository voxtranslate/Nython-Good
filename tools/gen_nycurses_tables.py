#!/usr/bin/env python3
"""tools/gen_nycurses_tables.py - writes src/builtins/nycurses_tables.inc and
the width block of lib/_nyvt.ny (round 84).

Everything comes from the system it runs on (Linux with ncurses 6 and glibc):
  - the terminfo capability names in term(5) order (libtinfo's boolnames,
    numnames, strnames arrays, read through ctypes),
  - ncurses' function-key table (_nc_tinfo_fkeys: which k* capability gives
    which KEY_* code) and the KEY_* names keyname() returns,
  - the column widths of every code point (glibc's wcwidth in C.UTF-8,
    which is what ncurses itself uses), as ranges of width 0 and width 2,
  - the compiled xterm-256color and vt100 entries, embedded as the built-in
    descriptions curses falls back to when no terminfo database exists
    (Windows).

    python3 tools/gen_nycurses_tables.py
"""
import ctypes
import locale
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def cap_names():
    lib = ctypes.CDLL("libtinfo.so.6")

    def arr(name):
        a = (ctypes.c_char_p * 600).in_dll(lib, name)
        out = []
        for p in a:
            if p is None:
                break
            out.append(p.decode())
        return out

    b, n, s = arr("boolnames"), arr("numnames"), arr("strnames")
    assert (len(b), len(n), len(s)) == (44, 39, 414), (len(b), len(n), len(s))

    class FK(ctypes.Structure):
        _fields_ = [("offset", ctypes.c_uint), ("code", ctypes.c_uint)]
    fk = (FK * 400).in_dll(lib, "_nc_tinfo_fkeys")
    keys = []
    for e in fk:
        if e.code == 0:
            break
        keys.append((e.offset, e.code))
    return b, n, s, keys


def key_names():
    # ncurses' own keyname(); curses.keyname needs initscr, the C one does not
    lib = ctypes.CDLL("libncursesw.so.6")
    lib.keyname.restype = ctypes.c_char_p
    names = {}
    for k in range(257, 512):
        v = lib.keyname(k)
        if v:
            names[k] = v.decode()
    return names


def widths():
    locale.setlocale(locale.LC_CTYPE, "C.UTF-8")
    libc = ctypes.CDLL("libc.so.6")
    w = libc.wcwidth
    w.argtypes = [ctypes.c_uint32]
    prev = None
    start = 0
    ranges = []
    for cp in range(0x110000):
        v = w(cp)
        if v < 0:
            v = 1      # controls and unassigned code points: one cell
        if cp == 0:
            v = 0
        if v != prev:
            if prev is not None:
                ranges.append((start, cp - 1, prev))
            prev = v
            start = cp
    ranges.append((start, 0x10FFFF, prev))
    zero = [(a, b) for a, b, v in ranges if v == 0]
    wide = [(a, b) for a, b, v in ranges if v == 2]
    return zero, wide


def blob(path):
    with open(path, "rb") as f:
        return f.read()


def c_bytes(name, data):
    out = ["static const unsigned char %s[%d] = {" % (name, len(data))]
    for i in range(0, len(data), 20):
        out.append("    " + ", ".join("0x%02x" % c for c in data[i:i + 20]) + ",")
    out.append("};")
    return "\n".join(out)


def main():
    b, n, s, keys = cap_names()
    kn = key_names()
    zero, wide = widths()
    xt = blob("/usr/share/terminfo/x/xterm-256color")
    vt = blob("/usr/share/terminfo/v/vt100")
    lines = []
    lines.append("// generated by tools/gen_nycurses_tables.py (round 84) - do not edit.")
    lines.append("// Capability names in term(5) order, ncurses' function-key table, the")
    lines.append("// KEY_* names, glibc's wcwidth as ranges, and the built-in terminfo")
    lines.append("// entries (xterm-256color, vt100 from ncurses' database).")
    lines.append("static const char* const TI_BOOLNAMES[%d] = {%s};" % (len(b), ", ".join('"%s"' % x for x in b)))
    lines.append("static const char* const TI_NUMNAMES[%d] = {%s};" % (len(n), ", ".join('"%s"' % x for x in n)))
    lines.append("static const char* const TI_STRNAMES[%d] = {" % len(s))
    for i in range(0, len(s), 12):
        lines.append("    " + ", ".join('"%s"' % x for x in s[i:i + 12]) + ",")
    lines.append("};")
    lines.append("struct TiFKey { unsigned short cap; unsigned short code; };")
    lines.append("static const TiFKey TI_FKEYS[%d] = {" % len(keys))
    for i in range(0, len(keys), 10):
        lines.append("    " + ", ".join("{%d, %d}" % k for k in keys[i:i + 10]) + ",")
    lines.append("};")
    lines.append("struct TiKeyName { unsigned short code; const char* name; };")
    items = sorted(kn.items())
    lines.append("static const TiKeyName TI_KEYNAMES[%d] = {" % len(items))
    for i in range(0, len(items), 6):
        lines.append("    " + ", ".join('{%d, "%s"}' % kv for kv in items[i:i + 6]) + ",")
    lines.append("};")
    for nm, rr in (("WC_ZERO", zero), ("WC_WIDE", wide)):
        lines.append("static const uint32_t %s[%d][2] = {" % (nm, len(rr)))
        for i in range(0, len(rr), 8):
            lines.append("    " + ", ".join("{0x%x, 0x%x}" % r for r in rr[i:i + 8]) + ",")
        lines.append("};")
    lines.append(c_bytes("TI_BUILTIN_XTERM256", xt))
    lines.append(c_bytes("TI_BUILTIN_VT100", vt))
    with open(os.path.join(ROOT, "src", "builtins", "nycurses_tables.inc"), "w") as f:
        f.write("\n".join(lines) + "\n")

    # the emulator's width table (between the markers in lib/_nyvt.ny)
    path = os.path.join(ROOT, "lib", "_nyvt.ny")
    if os.path.exists(path):
        with open(path) as f:
            src = f.read()
        a = src.index("# --- widths (generated) ---")
        z = src.index("# --- end widths ---")
        blk = ["# --- widths (generated) ---"]
        for nm, rr in (("_ZERO", zero), ("_WIDE", wide)):
            flat = []
            for r in rr:
                flat.append(r[0])
                flat.append(r[1])
            blk.append("%s = [" % nm)
            for i in range(0, len(flat), 12):
                blk.append("    " + ", ".join("0x%x" % v for v in flat[i:i + 12]) + ",")
            blk.append("]")
        src = src[:a] + "\n".join(blk) + "\n" + src[z:]
        with open(path, "w") as f:
            f.write(src)
    print("wrote", len(b), len(n), len(s), "caps,", len(keys), "keys,", len(zero), len(wide), "width ranges")


if __name__ == "__main__":
    main()
