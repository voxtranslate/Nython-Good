"""gen_tk_keysyms.py - lib/_tkinter/keysyms.ny from X11's keysymdef.h (round 84).

    python3 tools/gen_tk_keysyms.py /usr/include/X11/keysymdef.h lib/_tkinter/keysyms.ny

Tk on X11 resolves keysym names with XStringToKeysym, i.e. this file; the
groups kept are the ones Tk's own table (ks_names.h, used where there is no
Xlib) has: miscellany, XKB keys, Latin 1-4 and 9, Greek, Cyrillic, technical,
special, publishing and currency.
"""
import re
import sys

GROUPS = {"MISCELLANY", "XKB_KEYS", "LATIN1", "LATIN2", "LATIN3", "LATIN4", "LATIN9", "GREEK",
          "CYRILLIC", "TECHNICAL", "SPECIAL", "PUBLISHING", "CURRENCY"}

src, out = sys.argv[1], sys.argv[2]
cur = None
names = []
seen = set()
for line in open(src, encoding="latin-1"):
    m = re.match(r"#ifdef XK_(\w+)", line)
    if m:
        cur = m.group(1)
        continue
    if line.startswith("#endif"):
        cur = None
        continue
    m = re.match(r"#define XK_(\w+)\s+0x([0-9a-fA-F]+)", line)
    if m and cur in GROUPS:
        name, val = m.group(1), int(m.group(2), 16)
        if name not in seen:
            seen.add(name)
            names.append((name, val))
with open(out, "w") as f:
    f.write("# nython: module    (part of the _tkinter package: lib/_tkinter/)\n")
    f.write("# lib/_tkinter/keysyms.ny - X11 keysym names and numbers (round 84).\n")
    f.write("#\n")
    f.write("# Generated by tools/gen_tk_keysyms.py from X11's keysymdef.h: %d names in\n" % len(names))
    f.write("# the groups Tk's ks_names.h has (miscellany, XKB keys, Latin 1-4 and 9,\n")
    f.write("# Greek, Cyrillic, technical, special, publishing, currency).  A single\n")
    f.write("# character that is not here is its Unicode value (+0x1000000 above 0xff),\n")
    f.write("# as XStringToKeysym and Tk do.\n\n")
    f.write("KEYSYMS = {\n")
    for name, val in names:
        f.write('    "%s": 0x%x,\n' % (name, val))
    f.write("}\n")
print(len(names))
