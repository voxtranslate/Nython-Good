def hyp_want():
    # lib/doctest.ny's own report for HYP_SAMPLE, under this python3
    import subprocess
    import tempfile
    import shutil
    d = tempfile.mkdtemp(prefix="gen127_")
    try:
        shutil.copyfile(os.path.join(ROOT, "lib", "doctest.ny"), os.path.join(d, "doctest.py"))
        with open(os.path.join(d, "hyp127.py"), "w") as f:
            f.write(HYP_SAMPLE)
        with open(os.path.join(d, "hyp127_run.py"), "w") as f:
            f.write(HYP_RUNNER)
        r = subprocess.run([sys.executable, "hyp127_run.py"], cwd=d, capture_output=True, timeout=600)
        out = r.stdout.decode().replace(os.path.realpath(d) + os.sep, "").replace(d + os.sep, "")
        return [r.returncode, out]
    finally:
        shutil.rmtree(d, ignore_errors=True)


def main():
    ns = {"__name__": "__gen127__"}
    out = [HEADER, PREAMBLE]
    exec(PREAMBLE, ns)
    count = 0
    for e in E:
        if e[0] == "code":
            exec(e[1], ns)
            out.append(e[1].rstrip("\n") + "\n")
            continue
        name, expr, mod = e[1], e[2], e[3]
        try:
            v = eval(expr, ns)
        except Exception as ex:
            raise SystemExit("check %r failed under python3: %r" % (name, ex))
        want = repr(v)
        try:
            if eval(want, ns) != v:
                raise SystemExit("repr does not round-trip: %r -> %s" % (name, want[:200]))
        except SystemExit:
            raise
        except Exception as ex:
            raise SystemExit("repr does not evaluate: %r -> %s (%r)" % (name, want[:200], ex))
        line = "ck(%r, lambda: %s,\n   %s)\n" % (name, expr, want)
        if mod:
            line = "if have(%r):\n    " % mod + line.replace("\n   ", "\n       ")
        out.append(line)
        count += 1
    crypt_want = eval("crypt_table()", ns)
    import crypt as _c
    out.append("\nHYP_SAMPLE = %r\nHYP_RUNNER = %r\nHYP_WANT = %r\nCRYPT_WANT = %r\nCRYPT_PW5 = %r\n"
               % (HYP_SAMPLE, HYP_RUNNER, hyp_want(), crypt_want, _c.crypt("pw", "$5$abc$")))
    out.append(NYTHON_ONLY_TEMPLATE)
    out.append(FOOTER)
    exec(FOOTER.split("pass_n = 0")[0], ns)
    with open(os.path.join(ROOT, "examples", "vm_audit127.ny"), "w", encoding="utf-8") as f:
        f.write("".join(out))
    print(count, "checks generated")


