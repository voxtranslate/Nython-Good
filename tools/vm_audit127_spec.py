# The one thing in doctest's reports that cannot be the same: a traceback's
# frame in the doctest module itself (its path and line: /usr/lib/python3.11/
# doctest.py, line 1355 - lib/doctest.ny there), and the ~~^~~ lines CPython
# 3.11 puts under an expression's position. Both are cut from the reports,
# on every Python; everything else is compared as printed.
_TB_OWN = re.compile(r'^( *(?:[-+!?] *)?)File "[^"\n]*doctest\.(?:py|ny)", line \d+, in [^\n]*\n(?:\1  [^\n]*\n)?', re.M)
_TB_CARET = re.compile(r'^ *(?:[-+!?] *)?[~^]+ *\n', re.M)


def tbnorm(s):
    return _TB_CARET.sub("", _TB_OWN.sub("", s))


def child(args, inp=None):
    # [exit status, stdout] of this Python run with args in T (T's path cut
    # out of what it printed)
    r = subprocess.run([sys.executable] + ENGINE + args, cwd=T, capture_output=True, timeout=600, input=inp)
    out = r.stdout.decode("utf-8", "replace").replace("\r\n", "\n").replace(T + os.sep, "")
    return [r.returncode, tbnorm(out)]


def write(name, text):
    p = os.path.join(T, name)
    d = os.path.dirname(p)
    if not os.path.isdir(d):
        os.makedirs(d)
    with open(p, "w") as f:
        f.write(text)
    return p


def captured(f, *args, **kw):
    # what f(*args) printed, and its result
    buf = io.StringIO()
    with contextlib.redirect_stdout(buf):
        r = f(*args, **kw)
    if isinstance(r, tuple):
        r = tuple(r)   # doctest's TestResults as a plain tuple
    return [tbnorm(buf.getvalue().replace(T + os.sep, "")), r]


def plain(x):
    # named tuples as tuples, other objects as their repr: values both
    # Pythons write the same way
    if isinstance(x, tuple):
        return tuple(plain(v) for v in x)
    if isinstance(x, list):
        return [plain(v) for v in x]
    if isinstance(x, dict):
        return {plain(k): plain(v) for k, v in x.items()}
    if x is None or isinstance(x, (bool, int, float, str, bytes)):
        return x
    return repr(x)


def fresh(name):
    # import a module written into T, again
    sys.modules.pop(name, None)
    importlib.invalidate_caches()
    return importlib.import_module(name)

