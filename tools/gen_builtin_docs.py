#!/usr/bin/env python3
"""Generate lib/_nydocs.ny - CPython's docstrings for the builtins (round 84).

Run with the CPython whose texts the table should carry (3.11 in the
container, the version unicodedata's database and the stdlib ports follow):

    python3 tools/gen_builtin_docs.py > lib/_nydocs.ny

Keys: "len", "int", "int.bit_length", "ValueError", "math", "math.sqrt",
"sys", "sys.getrefcount" ... Texts shared by several keys are stored once
(`_T[i]`) - most dunder slots share theirs ("Return self+value.").
"""
import builtins, math, sys, time, cmath, types

def entries():
    out = {}
    def put(k, o):
        d = getattr(o, "__doc__", None)
        if isinstance(d, str) and d:
            out[k] = d
    put("builtins", builtins)
    for name in sorted(dir(builtins)):
        if name.startswith("_") and name not in ("__build_class__", "__import__"):
            continue
        o = getattr(builtins, name)
        put(name, o)
        if isinstance(o, type):
            for m, v in sorted(vars(o).items()):
                if m == "__doc__" or isinstance(v, (int, float, str, bytes, tuple)) or v is None:
                    continue
                put(name + "." + m, v)
    for t, tn in [(types.FunctionType, "function"), (types.MethodType, "method"),
                  (types.BuiltinFunctionType, "builtin_function_or_method"),
                  (types.GeneratorType, "generator"), (types.CoroutineType, "coroutine"),
                  (types.ModuleType, "module"), (type(None), "NoneType"),
                  (type(NotImplemented), "NotImplementedType"), (type(Ellipsis), "ellipsis"),
                  (types.CodeType, "code"), (types.FrameType, "frame"), (types.TracebackType, "traceback"),
                  (types.CellType, "cell"), (types.MappingProxyType, "mappingproxy"),
                  (types.SimpleNamespace, "SimpleNamespace")]:
        put(tn, t)
        for m, v in sorted(vars(t).items()):
            if m != "__doc__" and not isinstance(v, (int, float, str, bytes, tuple)) and v is not None:
                put(tn + "." + m, v)
    for mod in (math, cmath, sys, time):
        put(mod.__name__, mod)
        for name in sorted(dir(mod)):
            if name.startswith("_"):
                continue
            o = getattr(mod, name)
            if callable(o):
                put(mod.__name__ + "." + name, o)
    return out

def lit(s):
    # a Nython/Python string literal: escapes only, no ${ interpolation in a
    # `# nython: module` file
    r = s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n").replace("\t", "\\t")
    return '"' + r + '"'

def main():
    e = entries()
    texts, index = [], {}
    keys = {}
    for k in sorted(e):
        d = e[k]
        if d not in index:
            index[d] = len(texts)
            texts.append(d)
        keys[k] = index[d]
    w = sys.stdout.write
    w("# nython: module\n")
    w("# lib/_nydocs.ny - CPython %d.%d's docstrings of the builtins, the builtin\n" % sys.version_info[:2])
    w("# types and their methods, the builtin exceptions, and math/cmath/sys/time\n")
    w("# (round 84). Generated by tools/gen_builtin_docs.py - do not edit. The\n")
    w("# engines read a builtin's __doc__ through the prelude's _ny_builtin_doc,\n")
    w("# which imports this module the first time one is asked for.\n\n")
    w("_T = [\n")
    for t in texts:
        w("    " + lit(t) + ",\n")
    w("]\n\n")
    w("DOCS = {\n")
    for k in sorted(keys):
        w("    " + lit(k) + ": " + str(keys[k]) + ",\n")
    w("}\n\n")
    w("def doc(key):\n")
    w("    var i = DOCS.get(key)\n")
    w("    if i is None:\n")
    w("        return None\n")
    w("    return _T[i]\n")

main()
