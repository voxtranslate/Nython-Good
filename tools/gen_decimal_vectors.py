PRECS = [9, 16, 34]
lines = []


def run(op, args, prec, rnd):
    ctx = D.Context(prec=prec, rounding=RND[rnd], Emax=999999, Emin=-999999, traps=[])
    try:
        r = getattr(ctx, op)(*[D.Decimal(a) for a in args])
    except Exception as e:
        return None
    flags = ''.join(sorted(s.__name__[:3] for s in SIG if ctx.flags[s]))
    return str(r), flags


for prec in PRECS:
    for op, cases in bin_ops.items():
        for a, b in cases:
            rnds = ['he']
            if op in ('divide', 'quantize'):
                rnds = ['he', 'hu', 'd', 'c', 'f', 'u', 'hd', '05'] if prec == 9 else ['he']
            for rnd in rnds:
                res = run(op, (a, b), prec, rnd)
                if res:
                    lines.append('|'.join([op, str(prec), rnd, a, b, '', res[0], res[1]]))
    for op, cases in un_ops.items():
        for a in cases:
            rnds = ['he']
            if op in ('plus', 'to_integral_value'):
                rnds = ['he', 'hu', 'hd', 'u', 'd', 'c', 'f', '05']
            for rnd in rnds:
                res = run(op, (a,), prec, rnd)
                if res:
                    lines.append('|'.join([op, str(prec), rnd, a, '', '', res[0], res[1]]))
    for op, cases in ter_ops.items():
        for a, b, c in cases:
            res = run(op, (a, b, c), prec, 'he')
            if res:
                lines.append('|'.join([op, str(prec), 'he', a, b, c, res[0], res[1]]))

print('\n'.join(lines))
