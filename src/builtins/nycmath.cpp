// builtins/nycmath.cpp - the functions of Python's cmath module (round 83),
// for lib/cmath.ny.
//
// CPython's cmathmodule.c, algorithm for algorithm: Kahan's formulas for the
// inverse functions ("Branch Cuts for Complex Elementary Functions, or Much
// Ado About Nothing's Sign Bit"), sqrt with rescaling, log with log1p near
// |z| = 1 and rescaling of subnormal and huge arguments, the hyperbolic
// functions computed through exp(x - 1) * e where cosh(x) alone would
// overflow, and the same errno rules - so results agree with CPython's to
// the last bit where both use the C library's real functions, and every
// error (ValueError "math domain error", OverflowError "math range error")
// is raised where CPython raises it. For non-finite operands the result comes
// from the special-value tables of cmathmodule.c (the C99 Annex G values),
// held in nycmath_tables.inc - generated by asking CPython for each entry.
//
//   _cmath_call(name, re, im) -> [re, im]       acos acosh asin asinh atan atanh
//                                               cos cosh exp log log10 sin sinh
//                                               sqrt tan tanh
//   _cmath_log(re, im, base_re, base_im) -> [re, im]   (two-argument log)
//   _cmath_rect(r, phi) -> [re, im]   _cmath_abs(re, im) -> float (OverflowError)
//   _cmath_phase(re, im) -> float
#include "platform_compat.hpp"
#include "NythonExecutor.hpp"
#include "builtins/os.hpp"
#include "builtins/sysmods.hpp"
#include <cerrno>
#include <cfloat>
#include <cmath>
#include <cstring>

namespace {

#include "nycmath_tables.inc"

struct C { double real, imag; };

const double INF = HUGE_VAL;
const double PI = 3.14159265358979323846;
const double E_ = 2.7182818284590452354;
const double LN2 = 0.6931471805599453094;
const double LN10 = 2.302585092994045684;
const double CM_LARGE_DOUBLE = DBL_MAX / 4.;
const double CM_SQRT_LARGE_DOUBLE = std::sqrt(CM_LARGE_DOUBLE);
const double CM_LOG_LARGE_DOUBLE = std::log(CM_LARGE_DOUBLE);
const double CM_SQRT_DBL_MIN = std::sqrt(DBL_MIN);
const int CM_SCALE_UP = 2 * (DBL_MANT_DIG / 2) + 1;
const int CM_SCALE_DOWN = -(CM_SCALE_UP + 1) / 2;

thread_local int g_errno = 0;

int special_type(double d) {
    if (std::isfinite(d)) {
        if (d != 0) return std::copysign(1., d) == 1. ? 4 : 1;
        return std::copysign(1., d) == 1. ? 3 : 2;
    }
    if (std::isnan(d)) return 6;
    return std::copysign(1., d) == 1. ? 5 : 0;
}
C from_table(const uint64_t t[7][7][2], double re, double im) {
    const uint64_t* e = t[special_type(re)][special_type(im)];
    C r;
    std::memcpy(&r.real, &e[0], 8);
    std::memcpy(&r.imag, &e[1], 8);
    return r;
}
bool special(const C& z) { return !std::isfinite(z.real) || !std::isfinite(z.imag); }
C neg(C z) { return C{-z.real, -z.imag}; }

C c_sqrt(C z) {
    if (special(z)) { g_errno = 0; return from_table(SV_SQRT, z.real, z.imag); }
    C r;
    if (z.real == 0. && z.imag == 0.) { r.real = 0.; r.imag = z.imag; return r; }
    double ax = std::fabs(z.real), ay = std::fabs(z.imag), s, d;
    if (ax < DBL_MIN && ay < DBL_MIN) {
        ax = std::ldexp(ax, CM_SCALE_UP);
        s = std::ldexp(std::sqrt(ax + std::hypot(ax, std::ldexp(ay, CM_SCALE_UP))), CM_SCALE_DOWN);
    } else {
        ax /= 8.;
        s = 2. * std::sqrt(ax + std::hypot(ax, ay / 8.));
    }
    d = ay / (2. * s);
    if (z.real >= 0.) { r.real = s; r.imag = std::copysign(d, z.imag); }
    else { r.real = d; r.imag = std::copysign(s, z.imag); }
    g_errno = 0;
    return r;
}

C c_acos(C z) {
    if (special(z)) { g_errno = 0; return from_table(SV_ACOS, z.real, z.imag); }
    C r;
    if (std::fabs(z.real) > CM_LARGE_DOUBLE || std::fabs(z.imag) > CM_LARGE_DOUBLE) {
        r.real = std::atan2(std::fabs(z.imag), z.real);
        if (z.real < 0.) r.imag = -std::copysign(std::log(std::hypot(z.real / 2., z.imag / 2.)) + LN2 * 2., z.imag);
        else r.imag = std::copysign(std::log(std::hypot(z.real / 2., z.imag / 2.)) + LN2 * 2., -z.imag);
    } else {
        C s1 = c_sqrt(C{1. - z.real, -z.imag});
        C s2 = c_sqrt(C{1. + z.real, z.imag});
        r.real = 2. * std::atan2(s1.real, s2.real);
        r.imag = std::asinh(s2.real * s1.imag - s2.imag * s1.real);
    }
    g_errno = 0;
    return r;
}

C c_acosh(C z) {
    if (special(z)) { g_errno = 0; return from_table(SV_ACOSH, z.real, z.imag); }
    C r;
    if (std::fabs(z.real) > CM_LARGE_DOUBLE || std::fabs(z.imag) > CM_LARGE_DOUBLE) {
        r.real = std::log(std::hypot(z.real / 2., z.imag / 2.)) + LN2 * 2.;
        r.imag = std::atan2(z.imag, z.real);
    } else {
        C s1 = c_sqrt(C{z.real - 1., z.imag});
        C s2 = c_sqrt(C{z.real + 1., z.imag});
        r.real = std::asinh(s1.real * s2.real + s1.imag * s2.imag);
        r.imag = 2. * std::atan2(s1.imag, s2.real);
    }
    g_errno = 0;
    return r;
}

C c_asinh(C z) {
    if (special(z)) { g_errno = 0; return from_table(SV_ASINH, z.real, z.imag); }
    C r;
    if (std::fabs(z.real) > CM_LARGE_DOUBLE || std::fabs(z.imag) > CM_LARGE_DOUBLE) {
        if (z.imag >= 0.) r.real = std::copysign(std::log(std::hypot(z.real / 2., z.imag / 2.)) + LN2 * 2., z.real);
        else r.real = -std::copysign(std::log(std::hypot(z.real / 2., z.imag / 2.)) + LN2 * 2., -z.real);
        r.imag = std::atan2(z.imag, std::fabs(z.real));
    } else {
        C s1 = c_sqrt(C{1. + z.imag, -z.real});
        C s2 = c_sqrt(C{1. - z.imag, z.real});
        r.real = std::asinh(s1.real * s2.imag - s2.real * s1.imag);
        r.imag = std::atan2(z.imag, s1.real * s2.real - s1.imag * s2.imag);
    }
    g_errno = 0;
    return r;
}

C c_asin(C z) {
    C s = c_asinh(C{-z.imag, z.real});
    return C{s.imag, -s.real};
}

C c_atanh(C z) {
    if (special(z)) { g_errno = 0; return from_table(SV_ATANH, z.real, z.imag); }
    if (z.real < 0.) return neg(c_atanh(neg(z)));
    C r;
    double ay = std::fabs(z.imag), h;
    if (z.real > CM_SQRT_LARGE_DOUBLE || ay > CM_SQRT_LARGE_DOUBLE) {
        h = std::hypot(z.real / 2., z.imag / 2.);
        r.real = z.real / 4. / h / h;
        r.imag = -std::copysign(PI / 2., -z.imag);
        g_errno = 0;
    } else if (z.real == 1. && ay < CM_SQRT_DBL_MIN) {
        if (ay == 0.) { r.real = INF; r.imag = z.imag; g_errno = EDOM; }
        else {
            r.real = -std::log(std::sqrt(ay) / std::sqrt(std::hypot(ay, 2.)));
            r.imag = std::copysign(std::atan2(2., -ay) / 2, z.imag);
            g_errno = 0;
        }
    } else {
        r.real = std::log1p(4. * z.real / ((1 - z.real) * (1 - z.real) + ay * ay)) / 4.;
        r.imag = -std::atan2(-2. * z.imag, (1 - z.real) * (1 + z.real) - ay * ay) / 2.;
        g_errno = 0;
    }
    return r;
}

C c_atan(C z) {
    C s = c_atanh(C{-z.imag, z.real});
    return C{s.imag, -s.real};
}

C c_cosh(C z) {
    C r;
    if (special(z)) {
        if (std::isinf(z.real) && std::isfinite(z.imag) && z.imag != 0.) {
            if (z.real > 0) { r.real = std::copysign(INF, std::cos(z.imag)); r.imag = std::copysign(INF, std::sin(z.imag)); }
            else { r.real = std::copysign(INF, std::cos(z.imag)); r.imag = -std::copysign(INF, std::sin(z.imag)); }
        } else {
            r = from_table(SV_COSH, z.real, z.imag);
        }
        g_errno = (std::isinf(z.imag) && !std::isnan(z.real)) ? EDOM : 0;
        return r;
    }
    if (std::fabs(z.real) > CM_LOG_LARGE_DOUBLE) {
        double x1 = z.real - std::copysign(1., z.real);
        r.real = std::cos(z.imag) * std::cosh(x1) * E_;
        r.imag = std::sin(z.imag) * std::sinh(x1) * E_;
    } else {
        r.real = std::cos(z.imag) * std::cosh(z.real);
        r.imag = std::sin(z.imag) * std::sinh(z.real);
    }
    g_errno = (std::isinf(r.real) || std::isinf(r.imag)) ? ERANGE : 0;
    return r;
}

C c_cos(C z) { return c_cosh(C{-z.imag, z.real}); }

C c_exp(C z) {
    C r;
    if (special(z)) {
        if (std::isinf(z.real) && std::isfinite(z.imag) && z.imag != 0.) {
            if (z.real > 0) { r.real = std::copysign(INF, std::cos(z.imag)); r.imag = std::copysign(INF, std::sin(z.imag)); }
            else { r.real = std::copysign(0., std::cos(z.imag)); r.imag = std::copysign(0., std::sin(z.imag)); }
        } else {
            r = from_table(SV_EXP, z.real, z.imag);
        }
        g_errno = (std::isinf(z.imag) && (std::isfinite(z.real) || (std::isinf(z.real) && z.real > 0))) ? EDOM : 0;
        return r;
    }
    double l;
    if (z.real > CM_LOG_LARGE_DOUBLE) {
        l = std::exp(z.real - 1.);
        r.real = l * std::cos(z.imag) * E_;
        r.imag = l * std::sin(z.imag) * E_;
    } else {
        l = std::exp(z.real);
        r.real = l * std::cos(z.imag);
        r.imag = l * std::sin(z.imag);
    }
    g_errno = (std::isinf(r.real) || std::isinf(r.imag)) ? ERANGE : 0;
    return r;
}

C c_log(C z) {
    if (special(z)) { g_errno = 0; return from_table(SV_LOG, z.real, z.imag); }
    C r;
    double ax = std::fabs(z.real), ay = std::fabs(z.imag);
    if (ax > CM_LARGE_DOUBLE || ay > CM_LARGE_DOUBLE) {
        r.real = std::log(std::hypot(ax / 2., ay / 2.)) + LN2;
    } else if (ax < DBL_MIN && ay < DBL_MIN) {
        if (ax > 0. || ay > 0.) {
            r.real = std::log(std::hypot(std::ldexp(ax, DBL_MANT_DIG), std::ldexp(ay, DBL_MANT_DIG))) - DBL_MANT_DIG * LN2;
        } else {
            r.real = -INF;
            r.imag = std::atan2(z.imag, z.real);
            g_errno = EDOM;
            return r;
        }
    } else {
        double h = std::hypot(ax, ay);
        if (0.71 <= h && h <= 1.73) {
            double am = ax > ay ? ax : ay, an = ax > ay ? ay : ax;
            r.real = std::log1p((am - 1) * (am + 1) + an * an) / 2.;
        } else {
            r.real = std::log(h);
        }
    }
    r.imag = std::atan2(z.imag, z.real);
    g_errno = 0;
    return r;
}

C c_log10(C z) {
    C r = c_log(z);
    int e = g_errno;
    r.real = r.real / LN10;
    r.imag = r.imag / LN10;
    g_errno = e;
    return r;
}

C c_sinh(C z) {
    C r;
    if (special(z)) {
        if (std::isinf(z.real) && std::isfinite(z.imag) && z.imag != 0.) {
            if (z.real > 0) { r.real = std::copysign(INF, std::cos(z.imag)); r.imag = std::copysign(INF, std::sin(z.imag)); }
            else { r.real = -std::copysign(INF, std::cos(z.imag)); r.imag = std::copysign(INF, std::sin(z.imag)); }
        } else {
            r = from_table(SV_SINH, z.real, z.imag);
        }
        g_errno = (std::isinf(z.imag) && !std::isnan(z.real)) ? EDOM : 0;
        return r;
    }
    if (std::fabs(z.real) > CM_LOG_LARGE_DOUBLE) {
        double x1 = z.real - std::copysign(1., z.real);
        r.real = std::cos(z.imag) * std::sinh(x1) * E_;
        r.imag = std::sin(z.imag) * std::cosh(x1) * E_;
    } else {
        r.real = std::cos(z.imag) * std::sinh(z.real);
        r.imag = std::sin(z.imag) * std::cosh(z.real);
    }
    g_errno = (std::isinf(r.real) || std::isinf(r.imag)) ? ERANGE : 0;
    return r;
}

C c_sin(C z) {
    C s = c_sinh(C{-z.imag, z.real});
    return C{s.imag, -s.real};
}

C c_tanh(C z) {
    C r;
    if (special(z)) {
        if (std::isinf(z.real) && std::isfinite(z.imag) && z.imag != 0.) {
            r.real = z.real > 0 ? 1.0 : -1.0;
            r.imag = std::copysign(0., 2. * std::sin(z.imag) * std::cos(z.imag));
        } else {
            r = from_table(SV_TANH, z.real, z.imag);
        }
        g_errno = (std::isinf(z.imag) && std::isfinite(z.real)) ? EDOM : 0;
        return r;
    }
    if (std::fabs(z.real) > CM_LOG_LARGE_DOUBLE) {
        r.real = std::copysign(1., z.real);
        r.imag = 4. * std::sin(z.imag) * std::cos(z.imag) * std::exp(-2. * std::fabs(z.real));
    } else {
        double tx = std::tanh(z.real), ty = std::tan(z.imag), cx = 1. / std::cosh(z.real);
        double txty = tx * ty, denom = 1. + txty * txty;
        r.real = tx * (1. + ty * ty) / denom;
        r.imag = ((ty / denom) * cx) * cx;
    }
    g_errno = 0;
    return r;
}

C c_tan(C z) {
    C s = c_tanh(C{-z.imag, z.real});
    return C{s.imag, -s.real};
}

// complexobject.c's _Py_c_quot (Smith's algorithm)
C c_quot(C a, C b) {
    C r;
    double abs_breal = b.real < 0 ? -b.real : b.real;
    double abs_bimag = b.imag < 0 ? -b.imag : b.imag;
    if (abs_breal >= abs_bimag) {
        if (abs_breal == 0.0) { g_errno = EDOM; r.real = r.imag = 0.0; }
        else {
            double ratio = b.imag / b.real, denom = b.real + b.imag * ratio;
            r.real = (a.real + a.imag * ratio) / denom;
            r.imag = (a.imag - a.real * ratio) / denom;
        }
    } else if (abs_bimag >= abs_breal) {
        double ratio = b.real / b.imag, denom = b.real * ratio + b.imag;
        r.real = (a.real * ratio + a.imag) / denom;
        r.imag = (a.imag * ratio - a.real) / denom;
    } else {
        r.real = r.imag = std::nan("");
    }
    return r;
}

double c_abs(C z) {
    if (special(z)) {
        g_errno = 0;
        if (std::isinf(z.real)) return std::fabs(z.real);
        if (std::isinf(z.imag)) return std::fabs(z.imag);
        return std::nan("");
    }
    double r = std::hypot(z.real, z.imag);
    g_errno = std::isfinite(r) ? 0 : ERANGE;
    return r;
}

[[noreturn]] void math_error() {
    if (g_errno == EDOM) nyos::raise("ValueError", "math domain error");
    nyos::raise("OverflowError", "math range error");
}
double darg(std::vector<Value>& a, size_t i) {
    if (i >= a.size()) return 0.0;
    return nyos::to_num(a[i], 0.0);
}
Value cpair(NythonExecutor& E, C r) {
    std::vector<Value> v{Value(r.real), Value(r.imag)};
    return E.makeListValue(v);
}

} // namespace

std::vector<std::string> cmath_builtin_names() {
    return {"_cmath_call", "_cmath_log", "_cmath_rect", "_cmath_abs", "_cmath_phase"};
}

Value dispatch_cmath(NythonExecutor& E, const std::string& name, std::vector<Value>& a, Context* ctx) {
    (void)ctx;
    if (name == "_cmath_call") {
        std::string f = E.strOf(a[0]);
        C z{darg(a, 1), darg(a, 2)};
        g_errno = 0;
        C r;
        if (f == "sqrt") r = c_sqrt(z);
        else if (f == "exp") r = c_exp(z);
        else if (f == "log") r = c_log(z);
        else if (f == "log10") r = c_log10(z);
        else if (f == "acos") r = c_acos(z);
        else if (f == "acosh") r = c_acosh(z);
        else if (f == "asin") r = c_asin(z);
        else if (f == "asinh") r = c_asinh(z);
        else if (f == "atan") r = c_atan(z);
        else if (f == "atanh") r = c_atanh(z);
        else if (f == "cos") r = c_cos(z);
        else if (f == "cosh") r = c_cosh(z);
        else if (f == "sin") r = c_sin(z);
        else if (f == "sinh") r = c_sinh(z);
        else if (f == "tan") r = c_tan(z);
        else if (f == "tanh") r = c_tanh(z);
        else nyos::raise("ValueError", "unknown cmath function " + f);
        if (g_errno) math_error();
        return cpair(E, r);
    }
    if (name == "_cmath_log") {
        g_errno = 0;
        C x = c_log(C{darg(a, 0), darg(a, 1)});
        C y = c_log(C{darg(a, 2), darg(a, 3)});
        x = c_quot(x, y);
        if (g_errno) math_error();
        return cpair(E, x);
    }
    if (name == "_cmath_rect") {
        double r = darg(a, 0), phi = darg(a, 1);
        C z;
        g_errno = 0;
        if (!std::isfinite(r) || !std::isfinite(phi)) {
            if (std::isinf(r) && std::isfinite(phi) && phi != 0.) {
                if (r > 0) { z.real = std::copysign(INF, std::cos(phi)); z.imag = std::copysign(INF, std::sin(phi)); }
                else { z.real = -std::copysign(INF, std::cos(phi)); z.imag = -std::copysign(INF, std::sin(phi)); }
            } else {
                z = from_table(SV_RECT, r, phi);
            }
            g_errno = (r != 0. && !std::isnan(r) && std::isinf(phi)) ? EDOM : 0;
        } else if (phi == 0.0) {
            z.real = r;
            z.imag = r * phi;
        } else {
            z.real = r * std::cos(phi);
            z.imag = r * std::sin(phi);
        }
        if (g_errno) math_error();
        return cpair(E, z);
    }
    if (name == "_cmath_abs") {
        double r = c_abs(C{darg(a, 0), darg(a, 1)});
        if (g_errno) math_error();
        return Value(r);
    }
    if (name == "_cmath_phase") return Value(std::atan2(darg(a, 1), darg(a, 0)));
    return UNDEFINED_VALUE;
}
